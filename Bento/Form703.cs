        /// <summary>
        /// 主要部品リストマスタが変更されているかを返します。
        /// </summary>
        /// <returns>変更されている場合はtrue</returns>
        private bool HasChange()
        {
            // 主要部品リストマスタを比較
            DataSet ds = (DataSet)bindingSource1.DataSource;
            if (ds == null)
            {
                return false;
            }

            DataTable dt = ds.Tables["主要部品リストマスタ"];

            foreach (DataRow dr in dt.Rows)
            {
                switch (dr.RowState)
                {
                    case DataRowState.Added:        // 追加
                    case DataRowState.Modified:     // 変更
                    case DataRowState.Deleted:      // 削除
                        return true;
                }
            }
            return false;
        }

        /// <summary>
        /// 登録可能か？
        /// </summary>
        /// <returns>登録可能な場合はtrue</returns>
        private bool CanSave()
        {
            bool hasError = false;

            try
            {
                if (this.HasAuthEdit == false)
                {
                    MessageBox.Show(this, "編集できる権限がありません。", this.Text, MessageBoxButtons.OK, MessageBoxIcon.Exclamation);
                    return false;
                }

                DataSet ds = (DataSet)bindingSource1.DataSource;
                DataTable dt = ds.Tables["主要部品リストマスタ"];

                Dictionary<int, int> busyoSyuyoCountMap = new Dictionary<int, int>();   // 部署ごとの主要商品のカウント

                // 行数分ループ
                foreach (DataRow dr in dt.Rows)
                {
                    dr.ClearErrors();

                    // 削除された行についてはエラーチェックは不要
                    if (dr.RowState == DataRowState.Deleted)
                    {
                        continue;
                    }

                    SyuyoBuhin syuyoBuhin = new SyuyoBuhin(dr);

                    // 主要表示を計数
                    if (syuyoBuhin.主要商品フラグ == true)
                    {
                        if (busyoSyuyoCountMap.ContainsKey((int)syuyoBuhin.部署ＣＤ) == false)
                        {
                            busyoSyuyoCountMap[(int)syuyoBuhin.部署ＣＤ] = 0;
                        }
                        busyoSyuyoCountMap[(int)syuyoBuhin.部署ＣＤ]++;
                    }
                }

                if (hasError)
                {
                    MessageBox.Show(this, "入力にエラーがあります。", this.Text, MessageBoxButtons.OK, MessageBoxIcon.Exclamation);
                    return false;
                }

                // 主要部品として表示できる最大数を超えていないか？
                int syuyoBuhinMax = SystemMaster.GetSyuyoBuhinMax();
                foreach (int syuyoCount in busyoSyuyoCountMap.Values)
                {
                    if (syuyoCount > syuyoBuhinMax)
                    {
                        MessageBox.Show(this, string.Format("主要表示できる商品は１つの部署につき{0}個までです。", syuyoBuhinMax), this.Text, MessageBoxButtons.OK, MessageBoxIcon.Exclamation);
                        return false;
                    }
                }

                return true;
            }
            catch (BentoException)
            {
                throw;
            }
            catch (Exception ex)
            {
                log.Error(ex);
                History.Error(ex);
                throw new BentoException(ex);
            }
        }

        /// <summary>
        /// DB保存
        /// </summary>
        /// <returns>ダイアログを閉じる場合はtrue</returns>
        private bool Save()
        {
            try
            {
                bool ret = false;
                History.ProcessType historyProcess = History.ProcessType.Update;

                using (SqlConnection con = new SqlConnection(DBUtil.ConnectionString))
                {
                    con.Open();
                    SqlTransaction tran = con.BeginTransaction();
                    try
                    {
                        DataSet ds = (DataSet)bindingSource1.DataSource;
                        DataTable dt = ds.Tables["主要部品リストマスタ"];

                        foreach (DataRow dr in dt.Rows)
                        {
                            SyuyoBuhin syuyoBuhin = new SyuyoBuhin(dr);
                            switch (dr.RowState)
                            {
                                case DataRowState.Added:        // 追加
                                    historyProcess = History.ProcessType.Create;
                                    //ret = syuyoBuhin.Insert(con, tran);
                                    if (log.IsWarnEnabled) log.WarnFormat("主要部品リストマスタ追加({0})", syuyoBuhin.Code);
                                    ret = true;
                                    break;

                                case DataRowState.Modified:     // 変更
                                    historyProcess = History.ProcessType.Update;
                                    ret = syuyoBuhin.Update(con, tran);
                                    break;

                                case DataRowState.Deleted:      // 削除
                                    historyProcess = History.ProcessType.Delete;
                                    //ret = syuyoBuhin.Delete(con, tran);
                                    if (log.IsWarnEnabled) log.WarnFormat("主要部品リストマスタ削除({0})", syuyoBuhin.Code);
                                    ret = true;
                                    break;

                                default:
                                    ret = true;
                                    break;
                            }

                            if (ret == false)
                            {
                                MessageBox.Show(this, syuyoBuhin.Message, this.Text, MessageBoxButtons.OK, MessageBoxIcon.Error);
                                return false;
                            }

                            History.Save(con, tran, this.Text, "主要部品リストマスタ", syuyoBuhin.Code, historyProcess);
                        }

                        historyProcess = History.ProcessType.Update;

                        tran.Commit();
                        log.InfoFormat("主要部品リストマスタを{0}しました。", historyProcess.DisplayName());
                        MessageBox.Show(this, string.Format("{0}しました。", historyProcess.DisplayName()), this.Text, MessageBoxButtons.OK, MessageBoxIcon.Information);
                        return true;
                    }
                    catch (BentoException)
                    {
                        throw;
                    }
                    catch (Exception ex)
                    {
                        tran.Rollback();
                        log.Error(ex);
                        History.Error(ex);
                        throw new BentoException(ex);
                    }
                }
            }
            catch (BentoException)
            {
                throw;
            }
            catch (Exception ex)
            {
                log.Error(ex);
                History.Error(ex);
                throw new BentoException(ex);
            }
        }

