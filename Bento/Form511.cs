        /// <summary>
        /// データ取得
        /// </summary>
        private void GetData()
        {
            try
            {
                using (SqlConnection con = new SqlConnection(DBUtil.ConnectionString))
                {
                    con.Open();
                    SqlCommand cmd = con.CreateCommand();
                    cmd.CommandText = "\r\n SELECT" +
                                      "\r\n     企業ＣＤ" +
                                      "\r\n     ,請求番号" +
                                      "\r\n     ,得意先ＣＤ" +
                                      "\r\n     ,部署ＣＤ" +
                                      "\r\n     ,得意先名" +
                                      "\r\n     ,請求日" +
                                      "\r\n     ,請求先ＣＤ" +
                                      "\r\n     ,請求先名" +
                                      "\r\n     ,売上金額" +
                                      "\r\n     ,入金額" +
                                      "\r\n     ,作成担当者ＣＤ" +
                                      "\r\n     ,作成日" +
                                      "\r\n     ,修正担当者ＣＤ" +
                                      "\r\n     ,修正日" +
                                      "\r\n FROM" +
                                      "\r\n     電子決済請求ヘッダ" +
                                      "\r\n WHERE" +
                                      "\r\n     企業ＣＤ = @企業ＣＤ" +
                                      "\r\n     AND 請求番号 = @請求番号" +
                                      "\r\n ORDER BY" +
                                      "\r\n     得意先ＣＤ";

                    cmd.Parameters.Add("@企業ＣＤ", SqlDbType.Int).Value = TableBase._企業ＣＤ;
                    cmd.Parameters.Add("@請求番号", SqlDbType.Int).Value = _paySeikyuDetailCriteria.請求番号;

                    log.Debug(cmd.CommandTextWithParameters());

                    SqlDataAdapter adp = new SqlDataAdapter(cmd);

                    DataTable dt = new DataTable("電子決済請求明細");
                    adp.Fill(dt);

                    DataSet ds = new DataSet();
                    ds.Tables.Add(dt);

                    // 合計行を追加する
                    dt.Rows.Add(dt.NewRow());

                    // 数式を消すため、全行削除する
                    fpSpread1_Sheet1.Rows.Count = 0;

                    bindingSource1.DataSource = ds;
                    bindingSource1.DataMember = "電子決済請求明細";

                    log.Info("電子決済請求明細を検索しました。");
                }

                fpSpread1_Sheet1.BindDataColumn(TOKUISAKI_CD_COLUMN,   "得意先ＣＤ");
                fpSpread1_Sheet1.BindDataColumn(TOKUISAKI_NAME_COLUMN, "得意先名");
                fpSpread1_Sheet1.BindDataColumn(URIAGE_TOTAL_COLUMN,   "売上金額");
                fpSpread1_Sheet1.BindDataColumn(NUIKIN_TOTAL_COLUMN,   "入金額");

                // 最終行を固定行にする
                fpSpread1_Sheet1.FrozenTrailingRowCount = 1;
                fpSpread1_Sheet1.Rows[fpSpread1_Sheet1.Rows.Count - 1].BackColor = TOTAL_BACK_COLOR;
                fpSpread1_Sheet1.Rows[fpSpread1_Sheet1.Rows.Count - 1].CanFocus = false;
                fpSpread1_Sheet1.Cells[fpSpread1_Sheet1.Rows.Count - 1, TOKUISAKI_NAME_COLUMN].Text = "合計";

                // 合計行に数式を設定する
                if (fpSpread1_Sheet1.Rows.Count > 1)
                {
                    for (int columnIndex = URIAGE_TOTAL_COLUMN; columnIndex <= NUIKIN_TOTAL_COLUMN; columnIndex++)
                    {
                        FarPoint.Win.Spread.Cell topCell = fpSpread1_Sheet1.Cells[0, columnIndex];
                        FarPoint.Win.Spread.Cell bottomCell = fpSpread1_Sheet1.Cells[fpSpread1_Sheet1.Rows.Count - 2, columnIndex];
                        FarPoint.Win.Spread.Cell sumCell = fpSpread1_Sheet1.Cells[fpSpread1_Sheet1.Rows.Count - 1, columnIndex];
                        sumCell.Formula = string.Format("SUM({0}:{1})", topCell.ToString(), bottomCell.ToString());
                    }
                }

                fpSpread1.Focus();
                if (fpSpread1_Sheet1.Rows.Count != 0)
                {
                    // 検索→行を選択→検索→同じ行を選択 こうすると、bindingSource.Positionが反映されずに0のまま。
                    // （なので詳細画面を開くと、選択した行とは異なるレコードが表示される）
                    // どうも(暗示的／明示的に関わらず)bindingSource.Position=0の設定が無視されているようなので、いったん最終行をカレント行に設定する
                    fpSpread1_Sheet1.ActiveRowIndex = fpSpread1_Sheet1.Rows.Count - 1;
                    bindingSource1.Position = fpSpread1_Sheet1.Rows.Count - 1;

                    fpSpread1_Sheet1.ActiveRowIndex = 0;
                    bindingSource1.Position = 0;
                    fpSpread1_Sheet1.AddSelection(0, 0, 1, 1);  // 先頭行を選択
                }
            }
            catch (BentoException)
            {
                throw;
            }
            catch (Exception ex)
            {
                log.Error(ex);
                History.Error(ex);
                throw new BentoException(ex);
            }
        }

        /// <summary>
        /// 売上一覧表示
        /// </summary>
        private void ShowList()
        {
            try
            {
                DataRow dr = ((DataRowView)bindingSource1.Current).Row;
                int tokuisakiCD = (int)dr["得意先ＣＤ"];

                UriageListCriteria uriageListCriteria = new UriageListCriteria();
                uriageListCriteria.売上日From = _paySeikyuDetailCriteria.対象売上日From;
                uriageListCriteria.売上日To = _paySeikyuDetailCriteria.対象売上日To;
                uriageListCriteria.得意先ＣＤ = tokuisakiCD;
                uriageListCriteria.売上区分 = _paySeikyuDetailCriteria.売上区分;

                Form402 form = new Form402(uriageListCriteria);
                if (form.HasAuthBrowse == false)
                {
                    MessageBox.Show(this, "詳細画面を開く権限がありません。", this.Text, MessageBoxButtons.OK, MessageBoxIcon.Exclamation);
                    return;
                }
                // モーダルにせず、複数開けるようにする
                // SubFormOpenInit(form);
                form.MdiParent = this.MdiParent;
                form.Show();
            }
            catch (BentoException ex)
            {
                MessageBox.Show(this, ex.ToString(), this.Text, MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
            catch (Exception ex)
            {
                log.Error(ex);
                History.Error(ex);
                throw new BentoException(ex);
            }
            finally
            {
                this.MdiParent.Cursor = Cursors.Default;
            }
        }
