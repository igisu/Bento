        /// <summary>
        /// 検索ボタン
        /// </summary>
        /// <param name="sender"></param>
        /// <param name="e"></param>
        private void btnQuery_Click(object sender, EventArgs e)
        {
            try
            {
                // 検索条件の入力にエラーがある？
                if (_nyukinListCriteria.HasErrors)
                {
                    if (string.IsNullOrEmpty(_nyukinListCriteria.Error) == false)
                    {
                        MessageBox.Show(this, _nyukinListCriteria.Error, this.Text, MessageBoxButtons.OK, MessageBoxIcon.Exclamation);
                    }
                    return;
                }

                this.MdiParent.Cursor = Cursors.WaitCursor;

                using (SqlConnection con = new SqlConnection(DBUtil.ConnectionString))
                {
                    con.Open();
                    SqlCommand cmd = con.CreateCommand();

                    StringBuilder sql = new StringBuilder();

                    if ((int)cboListMax.SelectedValue < 0)
                    {
                        sql.AppendLine("SELECT");
                    }
                    else
                    {
                        sql.AppendFormat("SELECT TOP({0})", cboListMax.SelectedValue);
                    }
                    sql.AppendLine("     A.企業ＣＤ");
                    sql.AppendLine("     ,A.入金番号");
                    sql.AppendLine("     ,A.入金入力区分");
                    sql.AppendLine("     ,A.入金日");
                    sql.AppendLine("     ,A.部署ＣＤ");
                    sql.AppendLine("     ,B.部署名");
                    sql.AppendLine("     ,C.コースＣＤ");
                    sql.AppendLine("     ,C.コース名");
                    sql.AppendLine("     ,A.得意先ＣＤ");
                    sql.AppendLine("     ,A.得意先名");
                    sql.AppendLine("     ,A.依頼人ＣＤ");
                    sql.AppendLine("     ,A.振込依頼人名");
                    sql.AppendLine("     ,A.入金方法");
                    sql.AppendLine("     ,VN.入金方法名");
                    sql.AppendLine("     ,ISNULL(A.入金額, 0) AS 入金額");
                    sql.AppendLine("     ,A.入金摘要区分");
                    sql.AppendLine("     ,CONVERT(varchar, A.入金摘要区分) + '月分' AS 摘要");
                    sql.AppendLine("     ,A.対応請求番号");
                    sql.AppendLine("     ,A.TP決済番号");
                    sql.AppendLine("     ,A.TP取消決済番号");
                    sql.AppendLine("     ,A.備考");
                    sql.AppendLine("     ,A.作成担当者ＣＤ");
                    sql.AppendLine("     ,A1.担当者名 AS 作成担当者名");
                    sql.AppendLine("     ,A.作成日");
                    sql.AppendLine("     ,A.修正担当者ＣＤ");
                    sql.AppendLine("     ,A2.担当者名 AS 修正担当者名");
                    sql.AppendLine("     ,A.修正日");
                    sql.AppendLine(" FROM");
                    sql.AppendLine("     入金明細 AS A");
                    // -- 分配先の売上は分配元として計上したいので、得意先ＣＤを分配元のそれにすり替える
                    sql.AppendLine("     INNER JOIN 得意先マスタ AS S ON S.企業ＣＤ = A.企業ＣＤ AND S.得意先ＣＤ = A.得意先ＣＤ");
                    sql.AppendLine("     INNER JOIN 得意先マスタ AS J ON J.企業ＣＤ = S.企業ＣＤ AND J.得意先ＣＤ = ISNULL(S.受注得意先ＣＤ, S.得意先ＣＤ)");

                    if (_nyukinListCriteria.コースＣＤ != null)
                    {
                        // -- コースによる絞り込み用
                        // -- 同じ得意先に複数のコースが設定されている場合、そのいずれのコースを条件に指定しても、そのコースにぶら下がる得意先がヒットしないといけない。
                        sql.AppendLine("     INNER JOIN");
                        sql.AppendLine("         (SELECT DISTINCT");
                        sql.AppendLine("             CM.企業ＣＤ");
                        sql.AppendLine("             ,CM.部署ＣＤ");
                        sql.AppendLine("             ,CM.コース名");
                        sql.AppendLine("             ,CT.コースＣＤ");
                        sql.AppendLine("             ,CT.得意先ＣＤ");
                        sql.AppendLine("             ,CT.コース順");
                        sql.AppendLine("         FROM");
                        sql.AppendLine("             コースマスタ AS CM");
                        sql.AppendLine("             INNER JOIN コーステーブル AS CT ON");
                        sql.AppendLine("                 CM.企業ＣＤ = CT.企業ＣＤ");
                        sql.AppendLine("                 AND CM.コースＣＤ =  CT.コースＣＤ");
                        sql.AppendLine("         WHERE");
                        sql.AppendLine("             CT.コースＣＤ = @コースＣＤ");
                        sql.AppendLine("         ) AS C");
                        sql.AppendLine("         ON J.企業ＣＤ = C.企業ＣＤ");
                        sql.AppendLine("         AND A.部署ＣＤ = C.部署ＣＤ");     // 入金明細の部署と一致するものに限る
                        sql.AppendLine("         AND J.得意先ＣＤ = C.得意先ＣＤ");
                        cmd.Parameters.Add("@コースＣＤ", SqlDbType.Int).Value = _nyukinListCriteria.コースＣＤ;
                    }
                    else
                    {
                        // -- 検索条件にコースが指定されていない場合は、ヒットした得意先が持つコースのうち最小値を取得する
                        sql.AppendLine("     LEFT JOIN");
                        sql.AppendLine("         (SELECT");
                        sql.AppendLine("             CM.企業ＣＤ");
                        sql.AppendLine("             ,CM.部署ＣＤ");
                        sql.AppendLine("             ,CM.コース名");
                        sql.AppendLine("             ,CT1.コースＣＤ");
                        sql.AppendLine("             ,CT1.得意先ＣＤ");
                        sql.AppendLine("             ,CT1.コース順");
                        sql.AppendLine("         FROM");
                        sql.AppendLine("             コーステーブル AS CT1");
                        sql.AppendLine("             INNER JOIN");
                        sql.AppendLine("                 (SELECT");
                        sql.AppendLine("                     M.企業ＣＤ");
                        sql.AppendLine("                     ,M.部署ＣＤ");
                        sql.AppendLine("                     ,T.得意先ＣＤ");
                        sql.AppendLine("                     ,MIN(T.コースＣＤ) AS コースＣＤ");
                        sql.AppendLine("                 FROM");
                        sql.AppendLine("                     コースマスタ AS M");
                        sql.AppendLine("                     LEFT JOIN コーステーブル AS T ON");
                        sql.AppendLine("                         T.企業ＣＤ = M.企業ＣＤ");
                        sql.AppendLine("                         AND T.コースＣＤ = M.コースＣＤ");
                        sql.AppendLine("                 GROUP BY");
                        sql.AppendLine("                     M.企業ＣＤ");
                        sql.AppendLine("                     ,M.部署ＣＤ");
                        sql.AppendLine("                     ,T.得意先ＣＤ");
                        sql.AppendLine("                 ) AS CT2");
                        sql.AppendLine("                     ON CT2.企業ＣＤ = CT1.企業ＣＤ");
                        sql.AppendLine("                     AND CT2.得意先ＣＤ = CT1.得意先ＣＤ");
                        sql.AppendLine("                     AND CT2.コースＣＤ = CT1.コースＣＤ");
                        sql.AppendLine("             INNER JOIN コースマスタ AS CM");
                        sql.AppendLine("                 ON CM.企業ＣＤ = CT1.企業ＣＤ");
                        sql.AppendLine("                 AND CM.コースＣＤ =  CT1.コースＣＤ");
                        sql.AppendLine("         ) AS C");
                        sql.AppendLine("             ON J.企業ＣＤ = C.企業ＣＤ");
                        sql.AppendLine("             AND A.部署ＣＤ = C.部署ＣＤ");     // 入金明細の部署と一致するものに限る
                        sql.AppendLine("             AND J.得意先ＣＤ = C.得意先ＣＤ");
                    }

                    sql.AppendLine("     LEFT JOIN 部署マスタ AS B ON B.企業ＣＤ = A.企業ＣＤ AND B.部署ＣＤ = A.部署ＣＤ");
                    sql.AppendLine("     LEFT JOIN V_入金方法 AS VN ON VN.入金方法CD = A.入金方法");
                    sql.AppendLine("     LEFT JOIN 担当者マスタ AS A1 ON A1.企業ＣＤ = A.企業ＣＤ AND A.作成担当者ＣＤ = A1.担当者ＣＤ");
                    sql.AppendLine("     LEFT JOIN 担当者マスタ AS A2 ON A2.企業ＣＤ = A.企業ＣＤ AND A.修正担当者ＣＤ = A2.担当者ＣＤ");
                    sql.AppendLine(" WHERE");
                    sql.AppendLine("     A.企業ＣＤ = @企業ＣＤ");

                    cmd.Parameters.Add("@企業ＣＤ", SqlDbType.Int).Value = TableBase._企業ＣＤ;

                    if (_nyukinListCriteria.支店ＣＤ != null && _nyukinListCriteria.支店ＣＤ != -1)
                    {
                        sql.AppendLine(" and B.支店ＣＤ = @支店ＣＤ ");
                        cmd.Parameters.Add("@支店ＣＤ", SqlDbType.Int).Value = _nyukinListCriteria.支店ＣＤ;
                    }

                    if (_nyukinListCriteria.部署ＣＤ != null && _nyukinListCriteria.部署ＣＤ != -1)
                    {
                        sql.AppendLine(" and A.部署ＣＤ = @部署ＣＤ ");
                        cmd.Parameters.Add("@部署ＣＤ", SqlDbType.Int).Value = _nyukinListCriteria.部署ＣＤ;
                    }

                    if (_nyukinListCriteria.入金日From != null)
                    {
                        sql.AppendLine(" and A.入金日 >= @入金日From ");
                        cmd.Parameters.Add("@入金日From", SqlDbType.Date).Value = _nyukinListCriteria.入金日From;
                    }

                    if (_nyukinListCriteria.入金日To != null)
                    {
                        sql.AppendLine(" and A.入金日 <= @入金日To ");
                        cmd.Parameters.Add("@入金日To", SqlDbType.Date).Value = _nyukinListCriteria.入金日To;
                    }

                    if (_nyukinListCriteria.得意先ＣＤ != null && _nyukinListCriteria.得意先ＣＤ != -1)
                    {
                        sql.AppendLine(" and A.得意先ＣＤ = @得意先ＣＤ ");
                        cmd.Parameters.Add("@得意先ＣＤ", SqlDbType.Int).Value = _nyukinListCriteria.得意先ＣＤ;
                    }

                    if (_nyukinListCriteria.入金方法 != null && _nyukinListCriteria.入金方法 != -1)
                    {
                        sql.AppendLine(" and A.入金方法 = @入金方法 ");
                        cmd.Parameters.Add("@入金方法", SqlDbType.Int).Value = _nyukinListCriteria.入金方法;
                    }

                    // 登録修正日時Fromのみ入力
                    if (_nyukinListCriteria.登録修正日時From != null && _nyukinListCriteria.登録修正日時To == null)
                    {
                        sql.AppendLine(" and (A.作成日 >= @登録修正日時From OR A.修正日 >= @登録修正日時From)");
                        cmd.Parameters.Add("@登録修正日時From", SqlDbType.DateTime).Value = _nyukinListCriteria.登録修正日時From;
                    }

                    // 登録修正日時Toのみ入力
                    if (_nyukinListCriteria.登録修正日時From == null && _nyukinListCriteria.登録修正日時To != null)
                    {
                        sql.AppendLine(" and (A.作成日 <= @登録修正日時To OR A.修正日 <= @登録修正日時To)");
                        cmd.Parameters.Add("@登録修正日時To", SqlDbType.DateTime).Value = _nyukinListCriteria.登録修正日時To;
                    }

                    // 登録修正日時Fromと登録修正日時Toの両方とも入力
                    if (_nyukinListCriteria.登録修正日時From != null && _nyukinListCriteria.登録修正日時To != null)
                    {
                        sql.AppendLine(" and ((A.作成日 >= @登録修正日時From AND A.作成日 <= @登録修正日時To)");
                        sql.AppendLine("  or  (A.修正日 >= @登録修正日時From AND A.修正日 <= @登録修正日時To))");
                        cmd.Parameters.Add("@登録修正日時From", SqlDbType.DateTime).Value = _nyukinListCriteria.登録修正日時From;
                        cmd.Parameters.Add("@登録修正日時To", SqlDbType.DateTime).Value = _nyukinListCriteria.登録修正日時To;
                    }

                    sql.AppendLine("order by ");
                    sql.AppendFormat((string)cboSortKey.SelectedValue, rdoAsc.Checked ? "ASC" : "DESC");

                    cmd.CommandText = sql.ToString();

                    log.Debug(cmd.CommandTextWithParameters());

                    SqlDataAdapter adp = new SqlDataAdapter(cmd);

                    DataTable dt = new DataTable("入金一覧");
                    adp.Fill(dt);

                    DataSet ds = new DataSet();
                    ds.Tables.Add(dt);

                    // この時点の件数を表示する
                    lblCount.Text = String.Format("{0}件", dt.Rows.Count);

                    // 合計行を追加する
                    dt.Rows.Add(dt.NewRow());

                    // 数式を消すため、全行削除する
                    fpSpread1_Sheet1.Rows.Count = 0;

                    bindingSource1.DataSource = ds;
                    bindingSource1.DataMember = "入金一覧";

                    log.Info("入金一覧を検索しました。");
                }

                fpSpread1_Sheet1.BindDataColumn(NYUKIN_NO_COLUMN,      "入金番号");
                fpSpread1_Sheet1.BindDataColumn(NYUKINBI_COLUMN,       "入金日");
                fpSpread1_Sheet1.BindDataColumn(BUSYO_NAME_COLUMN,     "部署名");
                fpSpread1_Sheet1.BindDataColumn(COURSE_CD_COLUMN,      "コースＣＤ");
                fpSpread1_Sheet1.BindDataColumn(COURSE_NAME_COLUMN,    "コース名");
                fpSpread1_Sheet1.BindDataColumn(TOKUISAKI_CD_COLUMN,   "得意先ＣＤ");
                fpSpread1_Sheet1.BindDataColumn(TOKUISAKI_NAME_COLUMN, "得意先名");
                fpSpread1_Sheet1.BindDataColumn(NYUKIN_COLUMN,         "入金額");
                fpSpread1_Sheet1.BindDataColumn(TEKIYO_COLUMN,         "摘要");
                fpSpread1_Sheet1.BindDataColumn(NYUKIN_HOHO_COLUMN,    "入金方法名");
                fpSpread1_Sheet1.BindDataColumn(IRAININ_COLUMN,        "振込依頼人名");
                fpSpread1_Sheet1.BindDataColumn(BIKO_COLUMN,           "備考");

                // 背景色をリセット
                for (int rowIndex = 0; rowIndex < fpSpread1_Sheet1.Rows.Count; rowIndex++)
                {
                    fpSpread1_Sheet1.Rows[rowIndex].ResetBackColor();
                    fpSpread1_Sheet1.Rows[rowIndex].CanFocus = true;
                }

                // 最終行を固定行にする
                fpSpread1_Sheet1.FrozenTrailingRowCount = 1;
                fpSpread1_Sheet1.Rows[fpSpread1_Sheet1.Rows.Count - 1].BackColor = TOTAL_BACK_COLOR;
                fpSpread1_Sheet1.Rows[fpSpread1_Sheet1.Rows.Count - 1].CanFocus = false;
                fpSpread1_Sheet1.Cells[fpSpread1_Sheet1.Rows.Count - 1, TOKUISAKI_NAME_COLUMN].Text = "合計";

                // 合計行に数式を設定する
                if (fpSpread1_Sheet1.Rows.Count > 1)
                {
                    FarPoint.Win.Spread.Cell topCell = fpSpread1_Sheet1.Cells[0, NYUKIN_COLUMN];
                    FarPoint.Win.Spread.Cell bottomCell = fpSpread1_Sheet1.Cells[fpSpread1_Sheet1.Rows.Count - 2, NYUKIN_COLUMN];
                    FarPoint.Win.Spread.Cell sumCell = fpSpread1_Sheet1.Cells[fpSpread1_Sheet1.Rows.Count - 1, NYUKIN_COLUMN];
                    sumCell.Formula = string.Format("SUM({0}:{1})", topCell.ToString(), bottomCell.ToString());
                }

                fpSpread1.Focus();
                if (fpSpread1_Sheet1.Rows.Count != 0)
                {
                    // 検索→行を選択→検索→同じ行を選択 こうすると、bindingSource.Positionが反映されずに0のまま。
                    // （なので詳細画面を開くと、選択した行とは異なるレコードが表示される）
                    // どうも(暗示的／明示的に関わらず)bindingSource.Position=0の設定が無視されているようなので、いったん最終行をカレント行に設定する
                    // ※この画面はなぜか上記現象は発生しないが、処理を統一したいので適用している
                    fpSpread1_Sheet1.ActiveRowIndex = fpSpread1_Sheet1.Rows.Count - 1;
                    bindingSource1.Position = fpSpread1_Sheet1.Rows.Count - 1;

                    fpSpread1_Sheet1.ActiveRowIndex = 0;
                    bindingSource1.Position = 0;
                    fpSpread1_Sheet1.AddSelection(0, 0, 1, 1);  // 先頭行を選択
                }
            }
            catch (EmuException ex)
            {
                MessageBox.Show(this, ex.ToString(), this.Text, MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
            catch (Exception ex)
            {
                log.Error(ex);
                History.Error(ex);
                MessageBox.Show(this, "例外が発生しました。" + ex.ToString(), this.Text, MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
            finally
            {
                this.MdiParent.Cursor = Cursors.Default;
            }
        }

