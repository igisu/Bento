-- 月次得意先別実績一覧（対象商品）
-- 以下のように並べる
-- ┌─────┬─────┬─────┬───┐
-- │  商品Ａ  │  商品Ｂ  │  その他  │値引額│
-- ├──┬──┼──┬──┼──┬──┼───┤
-- │個数│金額│個数│金額│個数│金額│ 金額 │
-- └──┴──┴──┴──┴──┴──┴───┘
-- 商品ＣＤが
-- XXX:その他 YYY:合計
-- 商品ＣＤのアンダーバー以降は
-- 0:個数 1:金額

-- ①商品名（売上個数）
SELECT
    0 AS 値引区分
    ,0 AS その他区分
    ,A.商品ＣＤ AS ソート用商品ＣＤ
    ,CONVERT(varchar, A.商品ＣＤ) + '_0' AS 商品ＣＤ
    ,S.商品名略称
    ,'個数' AS 個数金額
FROM
    主要商品リストマスタ AS A
    LEFT JOIN 商品マスタ AS S ON S.企業ＣＤ = A.企業ＣＤ AND A.商品ＣＤ = S.商品ＣＤ
WHERE
    A.企業ＣＤ = @企業ＣＤ
    AND A.部署ＣＤ = @部署ＣＤ
    AND ISNULL(A.無効フラグ, 0) = 0
UNION
-- ②商品名（売上金額）
SELECT
    0 AS 値引区分
    ,0 AS その他区分
    ,A.商品ＣＤ AS ソート用商品ＣＤ
    ,CONVERT(varchar, A.商品ＣＤ) + '_1' AS 商品ＣＤ
    ,S.商品名略称
    ,'金額' AS 個数金額
FROM
    主要商品リストマスタ AS A
    LEFT JOIN 商品マスタ AS S ON S.企業ＣＤ = A.企業ＣＤ AND A.商品ＣＤ = S.商品ＣＤ
WHERE
    A.企業ＣＤ = @企業ＣＤ
    AND A.部署ＣＤ = @部署ＣＤ
    AND ISNULL(A.無効フラグ, 0) = 0
UNION
-- ③その他（売上個数）
SELECT
    0 AS 値引区分
    ,1 AS その他区分
    ,-1 AS ソート用商品ＣＤ
    ,'XXX_0' AS 商品ＣＤ
    ,'その他' AS 商品名略称
    ,'個数' AS 個数金額
UNION
-- ④その他（売上金額）
SELECT
    0 AS 値引区分
    ,1 AS その他区分
    ,-1 AS ソート用商品ＣＤ
    ,'XXX_1' AS 商品ＣＤ
    ,'その他' AS 商品名略称
    ,'金額' AS 個数金額
-- ⑤値引額
UNION
SELECT
    1 AS 値引区分
    ,0 AS その他区分
    ,-1 AS ソート用商品ＣＤ
    , 'YYY_1' AS 商品ＣＤ
    ,'値引額' AS 商品名略称
    ,'金額' AS 個数金額
ORDER BY
    値引区分
    ,その他区分
    ,ソート用商品ＣＤ
    ,商品ＣＤ
