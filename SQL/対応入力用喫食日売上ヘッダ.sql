-- スマホによる対応入力（商品にぶら下がる主食・副食をマスタとは異なる組み合わせで売ること）に対応すべく、
-- 売上が存在する注文は取得しない（注文に該当する売上が存在する場合は売上から取得する）ようにする。
-- 残数を取得するようなSQLには、そのインラインビューを組み込むこと。
-- ※このインラインビューと、注文ヘッダ・注文明細とを外部結合して、このインラインビューの売上明細がIS NULLであることをWHERE句に加える
(SELECT
   H.企業ＣＤ,
   H.売上日,
   H.得意先ＣＤ,
   H.部署ＣＤ,
   H.コースＣＤ,
   D.商品ＣＤ,
   D.明細番号
FROM
    -- 喫食日売上ヘッダ
    -- 指定した配送日の注文ヘッダ.喫食日＝売上ヘッダ.売上日の売上
    -- ※上記が存在しない場合は売上ヘッダ.売上日＝指定日の売上
    (SELECT
        T1.企業ＣＤ,
        T1.売上日,
        T1.得意先ＣＤ,
        T1.部署ＣＤ,
        T1.コースＣＤ
    FROM
        (SELECT
            企業ＣＤ,
            部署ＣＤ,
            コースＣＤ,
            得意先ＣＤ,
            喫食日 AS 売上日
        FROM
            注文ヘッダ
        WHERE
            企業ＣＤ     = @企業ＣＤ
            AND 配送日   = @注文日
            AND 部署ＣＤ = @部署ＣＤ
            AND コースＣＤ = @コースＣＤ
        ) T2 -- 注文ヘッダ（配送日から喫食日を売上とした注文ヘッダ）
        INNER JOIN 売上ヘッダ T1 ON
            T1.企業ＣＤ       = T2.企業ＣＤ
            AND T1.得意先ＣＤ = T2.得意先ＣＤ
            AND T1.売上日     = T2.売上日
            AND T1.部署ＣＤ   = T2.部署ＣＤ
            AND T1.コースＣＤ = T2.コースＣＤ
    UNION
    SELECT
        T1.企業ＣＤ,
        T1.売上日,
        T1.得意先ＣＤ,
        T1.部署ＣＤ,
        T1.コースＣＤ
    FROM
        売上ヘッダ T1
    WHERE
        T1.企業ＣＤ     = @企業ＣＤ
        AND T1.売上日   = @注文日
        AND T1.部署ＣＤ = @部署ＣＤ
        AND T1.コースＣＤ = @コースＣＤ
        AND NOT EXISTS (
            SELECT 'X'
            FROM
                (SELECT
                    企業ＣＤ,
                    部署ＣＤ,
                    コースＣＤ,
                    得意先ＣＤ,
                    喫食日 AS 売上日
                FROM
                    注文ヘッダ
                WHERE
                    企業ＣＤ     = @企業ＣＤ
                    AND 配送日   = @注文日
                    AND 部署ＣＤ = @部署ＣＤ
                    AND コースＣＤ = @コースＣＤ
                ) T2 -- 注文ヘッダ（配送日から喫食日を売上とした注文ヘッダ）
            WHERE
                T1.企業ＣＤ       = T2.企業ＣＤ
                AND T1.得意先ＣＤ = T2.得意先ＣＤ
                AND T1.売上日     = T2.売上日
                AND T1.部署ＣＤ   = T2.部署ＣＤ
                AND T1.コースＣＤ = T2.コースＣＤ)
    ) AS H
    INNER JOIN 売上明細 AS D
        ON D.企業ＣＤ    = H.企業ＣＤ
        AND D.売上日     = H.売上日
        AND D.得意先ＣＤ = H.得意先ＣＤ
        AND D.部署ＣＤ   = H.部署ＣＤ
) AS KHD
