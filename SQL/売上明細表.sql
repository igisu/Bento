-- 売上明細表
SELECT
    A.企業ＣＤ
    ,A.精算日
    ,A.部署ＣＤ
    ,A.コースＣＤ
    ,A.配送担当者ＣＤ
    ,A.配送担当者名
    ,A.部署名
    ,A.コース名
    ,ISNULL(M.チケット持出枚数, 0) AS チケット持出枚数
    ,ISNULL(M.チケット持出枚数, 0) - ISNULL(A.チケット束_売上枚数, 0) AS チケット持帰枚数
    ,ISNULL(A.チケット束_売上枚数, 0) AS チケット売上枚数
    ,ISNULL(A.チケット束_売上金額, 0) AS チケット売上金額
    ,ISNULL(A.現金_売上合計, 0) AS 現金_売上合計
    ,ISNULL(A.現金_値引合計, 0) AS 現金_値引合計
    ,ISNULL(A.現金_回収現金件数, 0) AS 現金_回収現金件数
    ,ISNULL(A.現金_回収現金, 0) AS 現金_回収現金
    ,ISNULL(A.現金_チケット束代, 0) AS 現金_チケット束代
    ,ISNULL(A.現金_本日現金合計, 0) AS 現金_本日現金合計
    ,ISNULL(A.掛売_売上合計, 0) AS 掛売_売上合計
    ,ISNULL(A.掛売_値引合計, 0) AS 掛売_値引合計
    ,ISNULL(A.掛売_未集金, 0) AS 掛売_未集金
    ,ISNULL(A.掛売_未集金外売上, 0) AS 掛売_未集金外売上
    ,ISNULL(A.掛売_本日掛売合計, 0) AS 掛売_本日掛売合計
    ,ISNULL(A.E_売上合計, 0) AS E_売上合計
    ,ISNULL(A.E_値引合計, 0) AS E_値引合計
    ,ISNULL(A.E_回収金額件数, 0) AS E_回収金額件数
    ,ISNULL(A.E_回収金額, 0) AS E_回収金額
    ,ISNULL(A.E_チケット束代, 0) AS E_チケット束代
    ,ISNULL(A.E_本日E合計, 0) AS E_本日E合計
    ,ISNULL(A.合計_本日総売上, 0) AS 合計_本日総売上
    ,ISNULL(A.合計_本日総値引, 0) AS 合計_本日総値引
    ,ISNULL(A.合計_チケット売上, 0) AS 合計_チケット売上
    ,ISNULL(A.合計_バークレー売上, 0) AS 合計_バークレー売上
    ,ISNULL(A.合計_実質総売上, 0) AS 合計_実質総売上
    ,ISNULL(A.消費チケ枚数_チケット, 0) AS 消費チケ枚数_チケット
    ,ISNULL(A.消費チケ枚数_ボーナス, 0) AS 消費チケ枚数_ボーナス
    ,ISNULL(A.消費チケ枚数_ＢＶ300, 0) AS 消費チケ枚数_ＢＶ300
    ,ISNULL(A.消費チケ枚数_ＢＶ200, 0) AS 消費チケ枚数_ＢＶ200
    ,ISNULL(A.消費チケ金額_ＢＶ300, 0) AS 消費チケ金額_ＢＶ300
    ,ISNULL(A.消費チケ金額_ＢＶ200, 0) AS 消費チケ金額_ＢＶ200
    ,ISNULL(A.金銭内訳_10000円, 0) AS 金銭内訳_10000円
    ,ISNULL(A.金銭内訳_5000円, 0) AS 金銭内訳_5000円
    ,ISNULL(A.金銭内訳_2000円, 0) AS 金銭内訳_2000円
    ,ISNULL(A.金銭内訳_1000円, 0) AS 金銭内訳_1000円
    ,ISNULL(A.金銭内訳_500円, 0) AS 金銭内訳_500円
    ,ISNULL(A.金銭内訳_100円, 0) AS 金銭内訳_100円
    ,ISNULL(A.金銭内訳_50円, 0) AS 金銭内訳_50円
    ,ISNULL(A.金銭内訳_10円, 0) AS 金銭内訳_10円
    ,ISNULL(A.金銭内訳_5円, 0) AS 金銭内訳_5円
    ,ISNULL(A.金銭内訳_1円, 0) AS 金銭内訳_1円
    ,ISNULL(A.金銭内訳_小切手, 0) AS 金銭内訳_小切手
    ,ISNULL(A.金銭内訳_領収書, 0) AS 金銭内訳_領収書
    ,ISNULL(A.金銭内訳_合計, 0) AS 金銭内訳_合計
    ,ISNULL(A.金銭内訳_過剰金, 0) AS 金銭内訳_過剰金
    ,A.作成担当者ＣＤ
    ,A1.担当者名 AS 作成担当者名
    ,A.作成日
    ,A.修正担当者ＣＤ
    ,A2.担当者名 AS 修正担当者名
    ,A.修正日
FROM
    売上精算_ヘッダ AS A
    LEFT JOIN 担当者マスタ AS A1 ON A1.企業ＣＤ = A.企業ＣＤ AND A.作成担当者ＣＤ = A1.担当者ＣＤ
    LEFT JOIN 担当者マスタ AS A2 ON A2.企業ＣＤ = A.企業ＣＤ AND A.修正担当者ＣＤ = A2.担当者ＣＤ
    LEFT JOIN 担当者マスタ AS A3 ON A2.企業ＣＤ = A.企業ＣＤ AND A.配送担当者ＣＤ = A3.担当者ＣＤ
    -- 売上明細表_チケット持出枚数
    LEFT JOIN (
        SELECT
            A.企業ＣＤ
            ,A.精算日
            ,A.部署ＣＤ
            ,A.コースＣＤ
            ,SUM(A.持出個数) AS チケット持出枚数
        FROM
            売上精算_持出明細 AS A
            LEFT JOIN 商品マスタ AS S ON S.企業ＣＤ = A.企業ＣＤ AND S.商品ＣＤ = A.商品ＣＤ
        WHERE
            A.企業ＣＤ       = @企業ＣＤ
            AND A.精算日     = @精算日
            AND A.部署ＣＤ   = @部署ＣＤ
            AND A.コースＣＤ = @コースＣＤ
            AND S.弁当区分   = @弁当区分チケット
        GROUP BY
            A.企業ＣＤ
            ,A.精算日
            ,A.部署ＣＤ
            ,A.コースＣＤ
    ) AS M
        ON M.企業ＣＤ    = A.企業ＣＤ
        AND M.精算日     = A.精算日
        AND M.部署ＣＤ   = A.部署ＣＤ
        AND M.コースＣＤ = A.コースＣＤ
WHERE
    A.企業ＣＤ   = @企業ＣＤ
AND A.精算日     = @精算日
AND A.部署ＣＤ   = @部署ＣＤ
AND A.コースＣＤ = @コースＣＤ




@企業ＣＤ = 34001
@精算日 = '2021/08/30'
@部署ＣＤ = 1
@コースＣＤ = 107
@弁当区分チケット = 8
