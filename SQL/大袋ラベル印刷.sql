-- 大袋ラベル印刷（セット）
SELECT
    VS.大袋ラベル食事区分名
    ,H.喫食日
    ,H.得意先ＣＤ
    -- ,M.商品ＣＤ
    ,SUM(M.商品数量) AS 商品数量
FROM
    注文ヘッダ AS H
    INNER JOIN 大袋ラベル印刷設定 AS OS
        ON OS.企業ＣＤ = H.企業ＣＤ
        AND OS.部署ＣＤ = H.部署ＣＤ
    INNER JOIN 注文明細 AS M
        ON  H.企業ＣＤ   = M.企業ＣＤ
        AND H.注文区分   = M.注文区分
        AND H.喫食日     = M.喫食日
        AND H.得意先ＣＤ = M.得意先ＣＤ
        AND H.部署ＣＤ   = M.部署ＣＤ
        AND M.商品ＣＤ   = OS.商品ＣＤ
    LEFT JOIN V_大袋ラベル食事区分 AS VS ON OS.大袋ラベル食事区分ＣＤ = VS.大袋ラベル食事区分ＣＤ
WHERE
    H.企業ＣＤ = @企業ＣＤ
    AND H.部署ＣＤ = @部署ＣＤ
    AND ISNULL(M.商品数量, 0) <> 0          -- 0注文はシールを印刷しない
    AND H.喫食日 = @注文日
    AND H.注文区分 = @注文区分注文
    AND OS.大袋ラベル印刷種別ＣＤ = @大袋ラベル印刷種別ＣＤセット
    AND OS.大袋ラベル食事区分ＣＤ = @大袋ラベル食事区分ＣＤ
GROUP BY
    VS.大袋ラベル食事区分名
    ,H.喫食日
    ,H.得意先ＣＤ




-- 大袋ラベル印刷（単品）
