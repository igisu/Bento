-- コース注文一覧（対象商品）
-- 以下のように並べる
-- ┌─────────────────┬─────────────────┐
-- │               注文               │               売上               │
-- ├─────┬─────┬─────┼─────┬─────┬─────┤
-- │  商品Ａ  │  商品Ｂ  │  その他  │  商品Ａ  │  商品Ｂ  │  その他  │
-- ├──┬──┼──┬──┼──┬──┼──┬──┼──┬──┼──┬──┤
-- │個数│金額│個数│金額│個数│金額│個数│金額│個数│金額│個数│金額│
-- └──┴──┴──┴──┴──┴──┴──┴──┴──┴──┴──┴──┘
-- 商品ＣＤのアンダーバー以降は
-- C:注文 U:売上
-- 0:個数 1:金額

-- ①商品名（注文個数）
SELECT
    0 AS 注文売上区分
    ,0 AS その他区分
    ,A.商品ＣＤ AS ソート用商品ＣＤ
    ,CONVERT(varchar, A.商品ＣＤ) + '_C0' AS 商品ＣＤ
    ,S.商品名略称
    ,'個数' AS 個数金額
FROM
    主要商品リストマスタ AS A
    LEFT JOIN 商品マスタ AS S ON S.企業ＣＤ = A.企業ＣＤ AND A.商品ＣＤ = S.商品ＣＤ
WHERE
    A.企業ＣＤ = 1
    AND A.部署ＣＤ = 1
    AND ISNULL(A.無効フラグ, 0) = 0
UNION
-- ②商品名（注文金額）
SELECT
    0 AS 注文売上区分
    ,0 AS その他区分
    ,A.商品ＣＤ AS ソート用商品ＣＤ
    ,CONVERT(varchar, A.商品ＣＤ) + '_C1' AS 商品ＣＤ
    ,S.商品名略称
    ,'金額' AS 個数金額
FROM
    主要商品リストマスタ AS A
    LEFT JOIN 商品マスタ AS S ON S.企業ＣＤ = A.企業ＣＤ AND A.商品ＣＤ = S.商品ＣＤ
WHERE
    A.企業ＣＤ = 1
    AND A.部署ＣＤ = 1
    AND ISNULL(A.無効フラグ, 0) = 0
UNION
-- ③その他（注文個数）
SELECT
    0 AS 注文売上区分
    ,1 AS その他区分
    ,-1 AS ソート用商品ＣＤ
    ,'XXX_C0' AS 商品ＣＤ
    ,'その他' AS 商品名略称
    ,'個数' AS 個数金額
UNION
-- ④その他（注文金額）
SELECT
    0 AS 注文売上区分
    ,1 AS その他区分
    ,-1 AS ソート用商品ＣＤ
    ,'XXX_C1' AS 商品ＣＤ
    ,'その他' AS 商品名略称
    ,'金額' AS 個数金額
UNION
-- ⑤商品名（売上個数）
SELECT
    1 AS 注文売上区分
    ,0 AS その他区分
    ,A.商品ＣＤ AS ソート用商品ＣＤ
    ,CONVERT(varchar, A.商品ＣＤ) + '_U0' AS 商品ＣＤ
    ,S.商品名略称
    ,'個数' AS 個数金額
FROM
    主要商品リストマスタ AS A
    LEFT JOIN 商品マスタ AS S ON S.企業ＣＤ = A.企業ＣＤ AND A.商品ＣＤ = S.商品ＣＤ
WHERE
    A.企業ＣＤ = 1
    AND A.部署ＣＤ = 1
    AND ISNULL(A.無効フラグ, 0) = 0
UNION
-- ⑥商品名（売上金額）
SELECT
    1 AS 注文売上区分
    ,0 AS その他区分
    ,A.商品ＣＤ AS ソート用商品ＣＤ
    ,CONVERT(varchar, A.商品ＣＤ) + '_U1' AS 商品ＣＤ
    ,S.商品名略称
    ,'金額' AS 個数金額
FROM
    主要商品リストマスタ AS A
    LEFT JOIN 商品マスタ AS S ON S.企業ＣＤ = A.企業ＣＤ AND A.商品ＣＤ = S.商品ＣＤ
WHERE
    A.企業ＣＤ = 1
    AND A.部署ＣＤ = 1
    AND ISNULL(A.無効フラグ, 0) = 0
UNION
-- ⑦その他（売上個数）
SELECT
    1 AS 注文売上区分
    ,1 AS その他区分
    ,-1 AS ソート用商品ＣＤ
    ,'XXX_U0' AS 商品ＣＤ
    ,'その他' AS 商品名略称
    ,'個数' AS 個数金額
UNION
-- ⑧その他（売上金額）
SELECT
    1 AS 注文売上区分
    ,1 AS その他区分
    ,-1 AS ソート用商品ＣＤ
    ,'XXX_U1' AS 商品ＣＤ
    ,'その他' AS 商品名略称
    ,'金額' AS 個数金額
ORDER BY
    注文売上区分
    ,その他区分
    ,ソート用商品ＣＤ
    ,商品ＣＤ
