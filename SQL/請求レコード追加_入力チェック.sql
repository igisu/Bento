-- 請求レコード追加_入力チェック

-- 同じ請求日、部署ＣＤ、請求先ＣＤが請求合計に存在しないこと
SELECT
    COUNT(請求番号) AS CNT
FROM
    請求合計
WHERE
    請求日 = @請求日
    AND 部署ＣＤ = @部署ＣＤ
    AND 請求先ＣＤ = @請求先ＣＤ


-- 請求先がいないこと（子でないこと）
-- 得意先マスタクラスを使えば済むので割愛


-- 最新の請求日のレコードしか作ってはダメ。（入力された請求日より新しいレコードが有ってはダメ）
SELECT
    COUNT(請求番号) AS CNT
FROM
    請求合計
WHERE
    請求日 > @請求日
    AND 部署ＣＤ = @部署ＣＤ
    AND 請求先ＣＤ = @請求先ＣＤ
