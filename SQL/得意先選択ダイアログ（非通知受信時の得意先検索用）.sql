    A.企業ＣＤ
    ,A.得意先ＣＤ
    ,A.得意先名
    ,A.得意先名カナ
    ,A.得意先名略称
    ,A.郵便番号
    ,A.住所1
    ,A.住所2
    ,A.電話番号1
    ,A.ＦＡＸ1
    ,A.電話番号2
    ,A.ＦＡＸ2
    ,A.お届け先郵便番号
    ,A.お届け先住所1
    ,A.お届け先住所2
    ,A.お届け先電話番号1
    ,A.お届け先ＦＡＸ1
    ,A.お届け先電話番号2
    ,A.お届け先ＦＡＸ2
    ,A.部署ＣＤ
    ,A.売掛現金区分
    ,A.電話確認区分
    ,A.締区分
    ,A.月締日
    ,A.週締曜日
    ,A.支払サイト
    ,A.支払日
    ,A.請求先ＣＤ
    ,A.支払方法
    ,A.振込手数料フラグ
    ,A.部署合算請求フラグ
    ,A.金融機関ＣＤ
    ,A.金融機関支店ＣＤ
    ,A.記号番号
    ,A.口座種別
    ,A.口座番号
    ,A.口座名義人
    ,A.チケット枚数
    ,A.サービスチケット枚数
    ,A.営業担当者ＣＤ
    ,A.獲得営業者ＣＤ
    ,A.登録担当者ＣＤ
    ,A.受注得意先ＣＤ
    ,A.受注方法
    ,A.電話確認時間_時
    ,A.電話確認時間_分
    ,A.味噌汁区分
    ,A.ふりかけ区分
    ,A.納品書発行区分
    ,A.空き容器回収区分
    ,A.請求書敬称
    ,A.備考１
    ,A.備考２
    ,A.備考３
    ,A.状態区分
    ,A.承認日
    ,A.承認者ＣＤ
    ,A.状態理由区分
    ,A.休日設定
    ,A.新規登録日
    ,A.税区分
    ,A.丸め処理区分
    ,A.祝日配送区分
    ,A.誕生日1
    ,A.誕生日2
    ,A.失客日
    ,A.EB銀行支店ＣＤ
    ,A.受注時特記事項
    ,A.請求書郵便マークフラグ
    ,A.集計ＣＤ
    ,A.配送得意先ＣＤ
    ,A.無効フラグ
    ,A.作成担当者ＣＤ
    ,A.作成日
    ,A.修正担当者ＣＤ
    ,A.修正日
    ,B.部署名
    ,VJ.表示順
    ,VJ.状態区分名
   -- 得意先に対するコース名を「、」区切りで取得
    ,REPLACE('START'+ISNULL(
       (SELECT
           '、' + CM.コース名
       FROM
            コーステーブル AS CT
            INNER JOIN コースマスタ AS CM
            ON CT.企業ＣＤ = CM.企業ＣＤ
            AND CT.コースＣＤ = CM.コースＣＤ
       WHERE
           CT.企業ＣＤ = A.企業ＣＤ
           AND CT.得意先ＣＤ = A.得意先ＣＤ
           AND ISNULL(CT.無効フラグ, 0) = 0
           AND ISNULL(CM.無効フラグ, 0) = 0
       ORDER BY
           CM.コース名
       FOR XML PATH ('')
       ),'、'),'START、','') AS コース名
FROM
    得意先マスタ AS A
    LEFT JOIN 担当者マスタ   AS A1 ON A1.企業ＣＤ = 40000 AND A.作成担当者ＣＤ = A1.担当者ＣＤ
    LEFT JOIN 担当者マスタ   AS A2 ON A2.企業ＣＤ = 40000 AND A.修正担当者ＣＤ = A2.担当者ＣＤ
    LEFT JOIN 部署マスタ     AS B  ON  B.企業ＣＤ = 40000 AND ISNULL(B.無効フラグ, 0) = 0  AND A.部署ＣＤ = B.部署ＣＤ
    LEFT JOIN V_状態区分     AS VJ ON A.状態区分 = VJ.状態区分CD
WHERE
    ISNULL(A.無効フラグ, 0) = 0
    AND A.企業ＣＤ = @企業ＣＤ
    AND (A.得意先名 like @得意先名 escape '#' OR A.得意先名カナ like @得意先名カナ escape '#' OR A.得意先名略称 like @得意先名略称 escape '#'
    OR replace(replace(A.得意先名, ' ', ''), '　', '') like @得意先名 escape '#'
    OR replace(replace(A.得意先名カナ, ' ', ''), '　', '') like @得意先名カナ escape '#'
    OR replace(replace(A.得意先名略称, ' ', ''), '　', '') like @得意先名略称 escape '#')
ORDER BY
    A.得意先名カナ

@企業ＣＤ = 40000
@得意先名 = 'リコー'
@得意先名カナ = 'リコー'
@得意先名略称 = 'リコー'
