-- 電子決済請求合計作成
-- 売上と入金から電子決済請求得意先単位で作成する。
-- 通常の請求は請求先から得意先が取得できるので、請求合計があれば必ず請求ヘッダもあるが、
-- 電子決済は請求先と得意先が無関係なので、電子決済請求合計があっても電子決済請求ヘッダがあるとは限らない。
-- ※とは言え、合計もヘッダも、売上と入金のいずれかが存在すれば作成するので、必ずどちらも存在することになるはず。
-- 締区分は常に月締め

--- 電子決済請求合計を削除
DELETE G
FROM
    電子決済請求合計 AS G
WHERE G.企業ＣＤ = @企業ＣＤ
AND G.請求日 = @請求日          -- 今回締日（入力された請求日）
AND G.締区分 = @締区分月締め    -- 常に月締め
AND G.売上区分 = @売上区分      -- 画面で指定された売上区分
AND G.請求先ＣＤ = @請求先ＣＤ



--- #電子決済請求合計Tempを作成
CREATE TABLE #電子決済請求合計Temp (
    請求日 date NOT NULL,
    締区分 int NOT NULL,
    売上区分 int NOT NULL,
    部署ＣＤ int NOT NULL,
    請求先ＣＤ int NULL,
    請求先名 varchar(100) COLLATE database_default NULL,
    入金額 decimal(20) NULL,
    買上金額 decimal(20) NULL,
    調整額 decimal(20) NULL,
    今回請求額 decimal(20) NULL,
    回収予定日 date NULL
)


--- #電子決済請求合計Tempに追加
INSERT INTO #電子決済請求合計Temp (
    請求日
    ,締区分
    ,売上区分
    ,部署ＣＤ
    ,請求先ＣＤ
    ,請求先名
    ,入金額         -- 電子決済請求ヘッダから
    ,買上金額       -- 電子決済請求ヘッダから
    ,調整額
    ,今回請求額     -- 電子決済請求ヘッダから
    ,回収予定日
) SELECT
      @請求日 AS 請求日
      ,@締区分月締め AS 締区分      -- 常に月締め
      ,@売上区分 AS 売上区分        -- 画面で指定された売上区分
      ,S.部署ＣＤ
      ,S.得意先ＣＤ AS 請求先ＣＤ
      ,S.得意先名 AS 請求先名
      ,0 AS 入金額
      ,0 AS 買上金額
      ,0 AS 調整額
      ,0 AS 今回請求額
      ,NULL AS 回収予定日       -- プログラム側にて算出する
  FROM
      -- 電子決済請求ヘッダの売上金額と入金額の合計を取得するので、ここではそれを格納するレコードを作るだけ
      得意先マスタ AS S
  WHERE
      S.企業ＣＤ = @企業ＣＤ
      AND S.得意先ＣＤ = @請求先ＣＤ


--- #電子決済請求ヘッダTempの売上金額、入金額の合計を算出し、#電子決済請求合計のTempの入金額、買上金額、今回請求額を更新
-- 通常の請求締めとは異なり、消費税は考慮不要
UPDATE G
SET G.入金額 = ISNULL(T.入金額, 0),
    G.買上金額 = ISNULL(T.売上金額, 0),
    G.今回請求額 = ISNULL(T.入金額, 0) + ISNULL(T.売上金額, 0)
FROM
    #電子決済請求合計Temp AS G
    LEFT JOIN
        (SELECT
            請求先ＣＤ
            ,SUM(売上金額) AS 売上金額
            ,SUM(入金額) AS 入金額
        FROM
            #電子決済請求ヘッダTemp
        GROUP BY
            請求先ＣＤ
        ) AS T
        ON G.請求先ＣＤ = T.請求先ＣＤ


--- #電子決済請求合計Tempを取得
SELECT
    G.請求日
    ,G.締区分
    ,G.売上区分
    ,G.部署ＣＤ
    ,G.請求先ＣＤ
    ,G.請求先名
    ,G.入金額
    ,G.買上金額
    ,G.調整額
    ,G.今回請求額
    ,ISNULL(T.支払サイト, 0) AS 支払サイト
    ,T.支払日
FROM
    #電子決済請求合計Temp AS G
    LEFT JOIN 得意先マスタ AS T ON T.企業ＣＤ = @企業ＣＤ and T.得意先ＣＤ = G.請求先ＣＤ
WHERE
    -- すべて0の場合は作成しない（ひとつでも0でなければ作成する）
    ISNULL(G.入金額, 0) <> 0
    OR ISNULL(G.買上金額, 0) <> 0
    OR ISNULL(G.調整額, 0) <> 0
    OR ISNULL(G.今回請求額, 0) <> 0
ORDER BY
    G.請求先ＣＤ



