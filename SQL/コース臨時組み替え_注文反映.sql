-- コース臨時組み替え_注文反映

-- 元に戻す（得意先にコースが複数有る場合は最小のコースＣＤ）
UPDATE 注文ヘッダ
SET コースＣＤ = CM.コースＣＤ
FROM
    注文ヘッダ AS CH
    INNER JOIN
        (SELECT
            CT.企業ＣＤ,
            CM.部署ＣＤ,
            CM.コース区分,
            CT.得意先ＣＤ,
            MIN(CT.コースＣＤ) AS コースＣＤ
        FROM
            コーステーブル AS CT
            INNER JOIN コースマスタ AS CM
                ON CM.企業ＣＤ = CT.企業ＣＤ
                AND CM.コースＣＤ = CT.コースＣＤ
        WHERE
            CT.企業ＣＤ = @企業ＣＤ
            AND ISNULL(CT.無効フラグ, 0) = 0
            AND CM.部署ＣＤ = @部署ＣＤ
            AND CM.コース区分 = @コース区分
            AND ISNULL(CM.無効フラグ, 0) = 0
        GROUP BY
            CT.企業ＣＤ,
            CM.部署ＣＤ,
            CM.コース区分,
            CT.得意先ＣＤ
        ) AS CM
        ON CM.企業ＣＤ = CH.企業ＣＤ
        AND CM.得意先ＣＤ = CH.得意先ＣＤ
    -- ┌────┬───┬───────┐
    -- │注文区分│部署  │コース        │
    -- ├────┼───┼───────┤
    -- │予測    │ランチ│ランチコース1 │
    -- ├────┼───┼───────┤
    -- │注文    │ランチ│夕食コース1   │
    -- └────┴───┴───────┘
    -- 上記のような注文があるときに夕食のコースを組み替えた場合、
    -- 夕食のコースのみが変わるべきである（ランチのコースは変わってはダメ）
    -- したがって（注文の部署ではなく）注文が持つコースの部署が検索条件と一致するレコードを更新対象にする
    INNER JOIN コースマスタ AS CM2
        ON CM2.企業ＣＤ = CH.企業ＣＤ
        AND CM2.コースＣＤ = CH.コースＣＤ
WHERE
    CH.配送日 = @配送日
    AND CM2.部署ＣＤ = @部署ＣＤ
--  AND CH.コースＣＤ = @コースＣＤ     -- 臨時コースを削除したときはここを有効にする


-- 臨時コースを注文に反映
UPDATE 注文ヘッダ
SET コースＣＤ = RM.コースＣＤ
FROM
    注文ヘッダ AS CH
    INNER JOIN
        (SELECT
            RT.企業ＣＤ,
            RM.部署ＣＤ,
            RM.コース区分,
            RT.得意先ＣＤ,
            RM.実施日,
            MIN(RT.コースＣＤ) AS コースＣＤ
        FROM
            臨時コーステーブル AS RT
            INNER JOIN 臨時コースマスタ AS RM
                ON RM.企業ＣＤ = RT.企業ＣＤ
                AND RM.コースＣＤ = RT.コースＣＤ
                AND RM.実施日 = RT.実施日
        WHERE
            RT.企業ＣＤ = @企業ＣＤ
            AND ISNULL(RT.無効フラグ, 0) = 0
            AND RM.実施日 = @配送日
            AND RM.部署ＣＤ = @部署ＣＤ
            AND RM.コース区分 = @コース区分
            AND ISNULL(RM.無効フラグ, 0) = 0
        GROUP BY
            RT.企業ＣＤ,
            RM.部署ＣＤ,
            RM.コース区分,
            RT.得意先ＣＤ,
            RM.実施日
        ) AS RM
        ON RM.企業ＣＤ = CH.企業ＣＤ
        AND RM.得意先ＣＤ = CH.得意先ＣＤ
        AND RM.実施日 = CH.配送日
    -- ┌────┬───┬───────┐
    -- │注文区分│部署  │コース        │
    -- ├────┼───┼───────┤
    -- │予測    │ランチ│ランチコース1 │
    -- ├────┼───┼───────┤
    -- │注文    │ランチ│夕食コース1   │
    -- └────┴───┴───────┘
    -- 上記のような注文があるときに夕食のコースを組み替えた場合、
    -- 夕食コース1が夕食コース2に変わるべきである（ランチコース1は変わってはダメ）
    -- したがって（注文の部署ではなく）注文が持つコースの部署が検索条件と一致するレコードを更新対象にする
    INNER JOIN 臨時コースマスタ AS RM2
        ON RM2.企業ＣＤ = CH.企業ＣＤ
        AND RM2.コースＣＤ = CH.コースＣＤ
        AND RM2.実施日 = CH.配送日
WHERE
    RM2.部署ＣＤ = @部署ＣＤ
