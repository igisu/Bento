    LEFT JOIN
        (SELECT
            C.得意先ＣＤ
            ,ISNULL(CONVERT(varchar, S.商品ＣＤ), 'XXX') AS 商品ＣＤ
            ,SUM(M.商品数量) AS 商品数量
        FROM
            売上明細 AS M
            -- 分配先の売上は分配元として計上したいので、得意先ＣＤを分配元のそれにすり替える
            INNER JOIN (
                SELECT
                    企業ＣＤ
                    ,得意先ＣＤ
                    ,ISNULL(受注得意先ＣＤ, 得意先ＣＤ) AS 受注得意先ＣＤ
                FROM
                    得意先マスタ
                ) AS T
                ON T.企業ＣＤ  = M.企業ＣＤ
                AND T.得意先ＣＤ = M.得意先ＣＤ
            -- 注文元の数量は配送先として計上する
            INNER JOIN 駆動表 AS C
                ON C.企業ＣＤ = T.企業ＣＤ
                AND C.コース得意先ＣＤ = T.受注得意先ＣＤ
            INNER JOIN 売上ヘッダ AS H
                ON  H.企業ＣＤ   = M.企業ＣＤ
