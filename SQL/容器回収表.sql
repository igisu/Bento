                AND H.得意先ＣＤ = M.得意先ＣＤ
                AND H.部署ＣＤ   = M.部署ＣＤ
            LEFT JOIN
                -- 出力できる商品の最大列数は16（その他(XXX)を入れて17）
                (SELECT TOP(16)
                    SS.企業ＣＤ
                    ,SS.商品ＣＤ
                    ,SS.部署ＣＤ
                FROM
                    主要商品リストマスタ AS SS
                    LEFT JOIN 商品マスタ AS SM ON SM.企業ＣＤ = SS.企業ＣＤ AND SM.商品ＣＤ = SS.商品ＣＤ
                WHERE
                    SS.企業ＣＤ = @企業ＣＤ
                    AND SS.部署ＣＤ = @部署ＣＤ
                    AND ISNULL(SS.無効フラグ, 0) = 0
                ORDER BY
                    CASE WHEN SS.商品グループＣＤ IS NULL THEN 1 ELSE 0 END
                    ,SS.商品グループＣＤ
                    ,SM.弁当区分
                    ,SS.商品ＣＤ
                ) AS S
                ON S.企業ＣＤ = M.企業ＣＤ
                AND S.商品ＣＤ = M.商品ＣＤ
                AND S.部署ＣＤ = M.部署ＣＤ
        WHERE
            H.企業ＣＤ = @企業ＣＤ
            AND H.売上日 = @売上日
            AND H.部署ＣＤ = @部署ＣＤ
        GROUP BY
            C.得意先ＣＤ
            ,S.商品ＣＤ
        ) AS A ON A.得意先ＣＤ = C.得意先ＣＤ
    LEFT JOIN 担当者マスタ AS D ON D.企業ＣＤ = C.企業ＣＤ AND D.担当者ＣＤ = C.担当者ＣＤ
    LEFT JOIN 部署マスタ AS B ON B.企業ＣＤ = C.企業ＣＤ AND B.部署ＣＤ = @部署ＣＤ
WHERE CM.コース区分 = @コース区分
