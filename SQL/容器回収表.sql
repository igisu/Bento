-- 商品名取得
-- 以下のように並べる
-- ┌───┬───┬───┐
-- │商品Ａ│商品Ｂ│その他│
-- └───┴───┴───┘
SELECT
    0 AS その他区分
    ,B.商品グループＣＤ
    ,B.商品ＣＤ AS ソート用商品ＣＤ
    ,CONVERT(varchar, B.商品ＣＤ) AS 商品ＣＤ
    ,B.商品名略称
FROM
    -- 出力できる商品の最大列数は16（その他を入れて17）
    (SELECT TOP(16)
        A.商品グループＣＤ
        ,A.商品ＣＤ
        ,S.商品名略称
    FROM
        主要商品リストマスタ AS A
        LEFT JOIN 商品マスタ AS S ON S.企業ＣＤ = A.企業ＣＤ AND A.商品ＣＤ = S.商品ＣＤ
    WHERE
        A.企業ＣＤ = @企業ＣＤ
        AND A.部署ＣＤ = @部署ＣＤ
        AND ISNULL(A.無効フラグ, 0) = 0
    ORDER BY
        CASE WHEN A.商品グループＣＤ IS NULL THEN 1 ELSE 0 END
        ,A.商品グループＣＤ
        ,S.弁当区分
        ,A.商品ＣＤ
    ) AS B
UNION
SELECT
    1 AS その他区分
    ,-1 AS 商品グループＣＤ
    ,-1 AS ソート用商品ＣＤ
    ,'XXX' AS 商品ＣＤ
    ,'その他' AS 商品名略称
ORDER BY
    その他区分
    ,商品グループＣＤ
    ,ソート用商品ＣＤ
    ,商品ＣＤ



-- 注文元の注文を配送先の注文に集約する対応として、注文元の得意先CDは配送先の得意先CDにすり替えて取得したい。
-- ただし、注文元のコースに配送先が属していない場合は、注文元はどこにも集約させずにそのまま取得するものとする。

-- ┌─┬─────────┬───────┬─────┬──────────────┐
-- │No│コースの得意先ＣＤ│配送得意先ＣＤ│集約先ＣＤ│最終的に取得したい得意先ＣＤ│
-- ├─┼─────────┼───────┼─────┼──────────────┤
-- │ 1│             43101│              │     43101│                       43101│
-- ├─┼─────────┼───────┼─────┼──────────────┤
-- │ 2│             43104│              │     43104│                       43104│
-- ├─┼─────────┼───────┼─────┼──────────────┤
-- │ 3│             43105│         43104│     43104│                       43104│
-- ├─┼─────────┼───────┼─────┼──────────────┤
-- │ 4│             43106│         43109│          │                       43106│
-- ├─┼─────────┼───────┼─────┼──────────────┤
-- │ 5│             43107│              │     43107│                       43107│
-- └─┴─────────┴───────┴─────┴──────────────┘
-- ・コースの得意先ＣＤが配送先を持たない（つまり注文元ではない）場合は、集約先ＣＤを採用する（1,2,5）
-- ・コースの得意先ＣＤが配送先を持つ（つまり注文元になる）場合は、集約先ＣＤを採用する（3）
-- ・コースの得意先ＣＤが配送先を持つ（つまり注文元になる）が、配送先がコースに属していない（集約先ＣＤがnullになっている）場合は、コースの得意先ＣＤを採用する（4）


WITH 対象コース得意先 AS (
-- コーステーブルから取得（実施日に該当する臨時コースマスタがあればコーステーブルからは取得しない。無ければ取得する）
SELECT
    CT.企業ＣＤ
    ,CT.コースＣＤ
    ,CM.コース名
    ,CM.担当者ＣＤ
    ,CT.得意先ＣＤ
    ,CT.コース順
FROM
    コーステーブル AS CT
    INNER JOIN コースマスタ AS CM ON CM.企業ＣＤ = CT.企業ＣＤ AND CM.コースＣＤ = CT.コースＣＤ AND ISNULL(CM.無効フラグ, 0) = 0
    LEFT JOIN
        (SELECT
            コースＣＤ
        FROM
            臨時コースマスタ
        WHERE
            企業ＣＤ = @企業ＣＤ
            AND ISNULL(無効フラグ, 0) = 0
            AND コースＣＤ >= @コースＣＤFrom
            AND コースＣＤ <= @コースＣＤTo
            AND 実施日 = @売上日
        ) AS RM
        ON RM.コースＣＤ = CT.コースＣＤ
WHERE
    CT.企業ＣＤ = @企業ＣＤ
    AND CT.コースＣＤ >= @コースＣＤFrom
    AND CT.コースＣＤ <= @コースＣＤTo
    AND ISNULL(CT.無効フラグ, 0) = 0
    AND RM.コースＣＤ IS NULL
-- 臨時コーステーブルから取得（実施日に該当する臨時コーステーブルがあれば取得する。無ければ取得しない）
UNION
SELECT
    RT.企業ＣＤ
    ,RT.コースＣＤ
    ,RM.コース名
    ,RM.担当者ＣＤ
    ,RT.得意先ＣＤ
    ,RT.コース順
FROM
    臨時コーステーブル AS RT
    INNER JOIN 臨時コースマスタ AS RM ON RM.企業ＣＤ = RT.企業ＣＤ AND RM.コースＣＤ = RT.コースＣＤ AND RT.実施日 = RM.実施日 AND ISNULL(RM.無効フラグ, 0) = 0
WHERE
    RT.企業ＣＤ = @企業ＣＤ
    AND RT.コースＣＤ >= @コースＣＤFrom
    AND RT.コースＣＤ <= @コースＣＤTo
    AND ISNULL(RT.無効フラグ, 0) = 0
    AND RT.実施日 = @売上日
)

,駆動表 AS (
SELECT DISTINCT
    D.企業ＣＤ
    ,D.コースＣＤ
    ,D.コース名
    ,D.コース得意先 AS コース得意先ＣＤ
    ,D.得意先ＣＤ
    ,D.担当者ＣＤ
    ,D.コース順
FROM
-- ①－１（指定されたコースにぶら下がる得意先(集約先)）
    (SELECT
        TH.企業ＣＤ
        ,TH.コースＣＤ
        ,TH.コース名
        ,TH.得意先ＣＤ AS コース得意先
        ,TH.配送得意先ＣＤ
        ,SY.集約先ＣＤ
        ,ISNULL(SY.集約先ＣＤ, TH.得意先ＣＤ) AS 得意先ＣＤ     -- 他SQLに提供する得意先ＣＤ
        ,TH.担当者ＣＤ
        ,TH.コース順 AS 得意先コース順
        ,SY.コース順 AS 集約先コース順
        ,ISNULL(SY.コース順, TH.コース順) AS コース順           -- 他SQLに提供するコース順
    FROM
    -- ①－１－１（指定されたコースにぶら下がる得意先と配送先）
        (SELECT
            W.企業ＣＤ
            ,W.得意先ＣＤ
            ,T.配送得意先ＣＤ
            ,W.コースＣＤ
            ,W.コース名
            ,W.担当者ＣＤ
            ,W.コース順
        FROM
            対象コース得意先 AS W
            -- 得意先と配送先を取得したいのでLEFT JOINしている
            LEFT JOIN 意先マスタ AS T
                ON T.企業ＣＤ = W.企業ＣＤ
                AND T.得意先ＣＤ = W.得意先ＣＤ
        ) AS TH
        -- ①－１－２（指定されたコースにぶら下がる得意先のうち、注文の集約先になりうる得意先を抽出）
        LEFT JOIN
            (SELECT DISTINCT
                W.企業ＣＤ
                ,W.得意先ＣＤ
                ,T.配送得意先ＣＤ AS 集約先ＣＤ
                ,W.コースＣＤ
                ,W.担当者ＣＤ
                ,W.コース順
            FROM
                対象コース得意先 AS W
                -- 集約先になりうる得意先のみを抽出したいのでINNER JOINしている
                -- ホントは 「ISNULL(配送得意先ＣＤ, 得意先ＣＤ) AS 配送得意先ＣＤ」 として取得したかったが、インデックスが効かなくなるので
                -- T.配送得意先ＣＤ には NULL を格納せず、代わりに得意先ＣＤを格納している
                INNER JOIN 得意先マスタ AS T
                    ON T.企業ＣＤ = W.企業ＣＤ
                    AND T.配送得意先ＣＤ = W.得意先ＣＤ
            ) AS SY
            ON ISNULL(TH.配送得意先ＣＤ, TH.得意先ＣＤ) = SY.集約先ＣＤ     -- 集約先と結合するのは配送先を優先する（集約先≒配送先なので）
    ) AS D
-- 以下の理由により、指定されたコースを持つ売上の得意先は取得しない。
-- ・分配処理を行うと、分配先の売上ヘッダのコースは（分配先が元々コースに属していなくても）分配元のコースになっている
-- ・容器回収表に出力するのは分配元のみにしたい
-- ・分配先の数量は分配元として計上するので、分配先は容器回収表に出力されなくてよい
-- ・売上時に指定したコースではなく、回収コースで出力することがある
-- したがってコーステーブル（臨時コーステーブル）に属している得意先を出力対象とするが、分配先がコースに属していれば、それが出力されるのは回避できない（回避しない）
)


