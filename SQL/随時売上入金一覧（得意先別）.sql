-- 随時売上入金一覧（得意先別）
SELECT
    A.部署ＣＤ
    ,B.部署名
    ,A.得意先ＣＤ AS ＣＤ
    ,T.得意先名 AS 名前
    ,U.売上
    ,N.入金
FROM
    -- ①駆動表（売上明細と入金明細のいずれかまたは両方にあるもの）
    (SELECT
        企業ＣＤ
        ,部署ＣＤ           -- 部署ごとに集計する場合はこちら
        ,NULL AS 部署ＣＤ   -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこちら
        ,得意先ＣＤ
    FROM
        売上明細
    WHERE
        企業ＣＤ = @企業ＣＤ
        AND 売上日 >= @指定年月日From
        AND 売上日 <= @指定年月日To
        AND 部署ＣＤ = @部署ＣＤ        -- 部署ごとに集計する場合のみ有効
        AND 得意先ＣＤ = @得意先ＣＤ
    UNION
    SELECT
        企業ＣＤ
        ,部署ＣＤ           -- 部署ごとに集計する場合はこちら
        ,NULL AS 部署ＣＤ   -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこちら
        ,得意先ＣＤ
    FROM
        入金明細
    WHERE
        企業ＣＤ = @企業ＣＤ
        AND 入金日 >= @指定年月日From
        AND 入金日 <= @指定年月日To
        AND 部署ＣＤ = @部署ＣＤ        -- 部署ごとに集計する場合のみ有効
        AND 得意先ＣＤ = @得意先ＣＤ
    ) AS A
    LEFT JOIN
    -- ②売上明細
    (SELECT
        企業ＣＤ
        ,部署ＣＤ           -- 部署ごとに集計する場合はこちら
        ,NULL AS 部署ＣＤ   -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこちら
        ,得意先ＣＤ
        ,SUM(値引後金額) AS 売上
    FROM
        売上明細
    WHERE
        企業ＣＤ = @企業ＣＤ
        AND 売上日 >= @指定年月日From
        AND 売上日 <= @指定年月日To
        AND 部署ＣＤ = @部署ＣＤ        -- 部署ごとに集計する場合のみ有効
        AND 得意先ＣＤ = @得意先ＣＤ
    GROUP BY
        企業ＣＤ
        ,部署ＣＤ                       -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこの行は不要
        ,得意先ＣＤ
    ) AS U ON A.企業ＣＤ = U.企業ＣＤ
           AND A.部署ＣＤ = U.部署ＣＤ  -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこの行は不要
           AND A.得意先ＣＤ = U.得意先ＣＤ
    LEFT JOIN
    -- ③入金明細
    (SELECT
        企業ＣＤ
        ,部署ＣＤ           -- 部署ごとに集計する場合はこちら
        ,NULL AS 部署ＣＤ   -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこちら
        ,得意先ＣＤ
        ,SUM(入金額) AS 入金
    FROM
        入金明細
    WHERE
        企業ＣＤ = @企業ＣＤ
        AND 入金日 >= @指定年月日From
        AND 入金日 <= @指定年月日To
        AND 部署ＣＤ = @部署ＣＤ        -- 部署ごとに集計する場合のみ有効
        AND 得意先ＣＤ = @得意先ＣＤ
    GROUP BY
        企業ＣＤ
        ,部署ＣＤ                       -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこの行は不要
        ,得意先ＣＤ
    ) AS N ON A.企業ＣＤ = N.企業ＣＤ
           AND A.部署ＣＤ = N.部署ＣＤ  -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこの行は不要
           AND A.得意先ＣＤ = N.得意先ＣＤ
    LEFT JOIN 部署マスタ AS B ON A.企業ＣＤ = B.企業ＣＤ AND A.部署ＣＤ = B.部署ＣＤ
    LEFT JOIN 得意先マスタ AS T ON A.企業ＣＤ = T.企業ＣＤ AND A.得意先ＣＤ = T.得意先ＣＤ
ORDER BY
    A.得意先ＣＤ

@企業ＣＤ = 40001
@指定年月日From = '2017/06/01'
@指定年月日To = '2017/06/30'
@部署ＣＤ = 1
@得意先ＣＤ = 8
