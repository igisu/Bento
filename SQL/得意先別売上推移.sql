-- 得意先別売上推移
SELECT
    0 AS 明細合計区分
    ,A.部署ＣＤ
    ,B.部署名
    ,C.コースＣＤ
    ,C.コース名
    ,A.得意先ＣＤ
    ,T.得意先名
    ,(A.集計年 * 100) + A.集計月 AS 年月
    ,A.金額
FROM
    -- 年月ごとの金額
    (SELECT
        U.企業ＣＤ
        ,U.部署ＣＤ         -- 部署ごとに集計する場合はこちら
        ,NULL AS 部署ＣＤ   -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこちら
        ,U.集計年
        ,U.集計月
        ,U.得意先ＣＤ
        ,J.得意先ＣＤ AS 受注得意先ＣＤ
        ,SUM(U.今月売上額) AS 金額
    FROM
        月次売上集計 AS U
        -- 分配先の売上は分配元として計上したいので、得意先ＣＤを分配元のそれにすり替える
        INNER JOIN 得意先マスタ AS T ON T.企業ＣＤ = U.企業ＣＤ AND T.得意先ＣＤ = U.得意先ＣＤ
        INNER JOIN 得意先マスタ AS J ON J.企業ＣＤ = T.企業ＣＤ AND J.得意先ＣＤ = ISNULL(T.受注得意先ＣＤ, T.得意先ＣＤ)
    WHERE
        U.企業ＣＤ = @企業ＣＤ
        AND ((U.集計年 * 100) + U.集計月) >= @集計年月From
        AND ((U.集計年 * 100) + U.集計月) <= @集計年月To
        AND U.部署ＣＤ = @部署ＣＤ      -- 部署ごとに集計する場合のみ有効
        AND U.得意先ＣＤ = @得意先ＣＤ
    GROUP BY
        U.企業ＣＤ
        ,U.部署ＣＤ         -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこの行は不要
        ,U.集計年
        ,U.集計月
        ,U.得意先ＣＤ
        ,J.得意先ＣＤ
    UNION
    -- 合計列
    SELECT
        U.企業ＣＤ
        ,U.部署ＣＤ         -- 部署ごとに集計する場合はこちら
        ,NULL AS 部署ＣＤ   -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこちら
        ,9999 AS 集計年
        ,99 AS 集計月
        ,U.得意先ＣＤ
        ,J.得意先ＣＤ AS 受注得意先ＣＤ
        ,SUM(U.今月売上額) AS 金額
    FROM
        月次売上集計 AS U
        -- 分配先の売上は分配元として計上したいので、得意先ＣＤを分配元のそれにすり替える
        INNER JOIN 得意先マスタ AS T ON T.企業ＣＤ = U.企業ＣＤ AND T.得意先ＣＤ = U.得意先ＣＤ
        INNER JOIN 得意先マスタ AS J ON J.企業ＣＤ = T.企業ＣＤ AND J.得意先ＣＤ = ISNULL(T.受注得意先ＣＤ, T.得意先ＣＤ)
    WHERE
        U.企業ＣＤ = @企業ＣＤ
        AND ((U.集計年 * 100) + U.集計月) >= @集計年月From
        AND ((U.集計年 * 100) + U.集計月) <= @集計年月To
        AND U.部署ＣＤ = @部署ＣＤ      -- 部署ごとに集計する場合のみ有効
        AND U.得意先ＣＤ = @得意先ＣＤ
    GROUP BY
        U.企業ＣＤ
        ,U.部署ＣＤ         -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこの行は不要
        ,U.得意先ＣＤ
        ,J.得意先ＣＤ
    ) AS A

    -- コースによる絞り込み用
    -- 同じ得意先に複数のコースが設定されている場合、そのいずれのコースを条件に指定しても、そのコースにぶら下がる得意先がヒットしないといけない。
    -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合は追加しない
    INNER JOIN
        (SELECT DISTINCT
            CM.企業ＣＤ
            ,CM.部署ＣＤ
            ,CM.コース名
            ,CM.コースＣＤ
            ,CT.得意先ＣＤ
            ,CT.コース順
        FROM
            コースマスタ AS CM
            INNER JOIN コーステーブル AS CT ON
                CM.企業ＣＤ = CT.企業ＣＤ
                AND CM.コースＣＤ =  CT.コースＣＤ
        WHERE
            CT.コースＣＤ = @コースＣＤ
        ) AS C
        ON A.企業ＣＤ = C.企業ＣＤ
        AND A.部署ＣＤ = C.部署ＣＤ     -- 月次売上集計の部署と一致するものに限る
        AND A.受注得意先ＣＤ = C.得意先ＣＤ

    -- 検索条件にコースが指定されていない場合は、ヒットした得意先が持つコースのうち最小値を取得する
    -- （コース注文一覧／コース売上一覧とは異なり、コースが指定されていない＝コースがnullの注文/売上 ではなく、コースを条件に加えない ということ）
    -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合は追加する
    LEFT JOIN
        (SELECT
            CM.企業ＣＤ
--            ,CM.部署ＣＤ      -- 部署ごとに集計しない（＝部署は考慮しない）ので、部署は無視してコースを取得する（以下同様）
            ,CM.コース名
            ,CT1.コースＣＤ
            ,CT1.得意先ＣＤ
            ,CT1.コース順
        FROM
            コーステーブル AS CT1
            INNER JOIN
                (SELECT
                    M.企業ＣＤ
--                    ,M.部署ＣＤ
                    ,T.得意先ＣＤ
                    ,MIN(T.コースＣＤ) AS コースＣＤ
                FROM
                    コースマスタ AS M
                    LEFT JOIN コーステーブル AS T ON
                        T.企業ＣＤ = M.企業ＣＤ
                        AND T.コースＣＤ = M.コースＣＤ
                GROUP BY
                    M.企業ＣＤ
--                    ,M.部署ＣＤ
                    ,T.得意先ＣＤ
                ) AS CT2
                    ON CT2.企業ＣＤ = CT1.企業ＣＤ
                    AND CT2.得意先ＣＤ = CT1.得意先ＣＤ
                    AND CT2.コースＣＤ = CT1.コースＣＤ
            INNER JOIN コースマスタ AS CM
                ON CM.企業ＣＤ = CT1.企業ＣＤ
                AND CM.コースＣＤ =  CT1.コースＣＤ
        ) AS C
        ON A.企業ＣＤ = C.企業ＣＤ
        AND A.受注得意先ＣＤ = C.得意先ＣＤ


    LEFT JOIN 部署マスタ AS B
        ON B.企業ＣＤ = A.企業ＣＤ
        AND B.部署ＣＤ = A.部署ＣＤ
    LEFT JOIN 得意先マスタ AS T
        ON T.企業ＣＤ = A.企業ＣＤ
        AND T.得意先ＣＤ = A.得意先ＣＤ

UNION
-- 合計行
SELECT
    1 AS 明細合計区分
    ,NULL AS 部署ＣＤ
    ,'' AS 部署名
    ,NULL AS コースＣＤ
    ,'' AS コース名
    ,NULL AS 得意先ＣＤ
    ,'合計' AS 得意先名
    ,NULL AS 年月
    ,NULL AS 金額
ORDER BY
    明細合計区分
    ,部署ＣＤ
    ,コースＣＤ
    ,得意先ＣＤ


@企業ＣＤ = 40001
@集計年月From = 201606
@集計年月To = 201705
@部署ＣＤ = 1
@得意先ＣＤ = 269
@コースＣＤ = 1
