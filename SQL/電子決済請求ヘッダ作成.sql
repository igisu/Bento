-- 電子決済請求ヘッダ作成
-- 売上と入金から得意先単位で作成
-- 分配については全く考慮しない（配送先・注文元とは両立しないので）
-- 売上区分に該当する電子決済請求得意先マスタの得意先に対して作成する。つまり部署ごとに作成することはない。部署ＣＤには売上の部署ではなく得意先の部署を格納する。
-- 締区分は常に月締め

--- 電子決済請求ヘッダを削除
-- 削除対象の電子決済請求合計と同じ請求番号を持つ電子決済請求ヘッダを削除する
DELETE H
FROM
    電子決済請求ヘッダ AS H
    INNER JOIN 電子決済請求合計 AS G ON G.企業ＣＤ = H.企業ＣＤ AND G.請求番号 = H.請求番号
WHERE G.企業ＣＤ = @企業ＣＤ
AND G.請求日 = @請求日          -- 今回締日（入力された請求日）
AND G.締区分 = @締区分月締め    -- 常に月締め
AND G.売上区分 = @売上区分      -- 画面で指定された売上区分
AND G.請求先ＣＤ = @請求先ＣＤ



--- #電子決済請求ヘッダTempを作成
-- 通常の請求締めとは異なり、消費税を考慮する必要が無いので、税区分と丸め処理区分は持たない。
CREATE TABLE #電子決済請求ヘッダTemp (
    得意先ＣＤ int NOT NULL,
    部署ＣＤ int NOT NULL,
    得意先名 varchar(100) COLLATE database_default NULL,
    請求日 date NOT NULL,
    請求先ＣＤ int NULL,
    請求先名 varchar(100) COLLATE database_default NULL,
    売上金額 decimal(18, 0) NULL
    入金額 decimal(18, 0) NULL
)


--- #電子決済請求ヘッダTempに出力するデータを取得
SELECT
    B.得意先ＣＤ
    ,T.部署ＣＤ     -- 売上の部署ではなく、得意先の部署
    ,T.得意先名
    ,@請求日 AS 請求日
    ,@請求先ＣＤ AS 請求先ＣＤ
    ,@請求先名 AS 請求先名
    ,B.売上金額
    ,B.入金額
FROM
    -- 売上と入金から電子決済請求ヘッダを作る
    -- 売上については、前回請求が有るものは前回請求日以降のものを、無ければ2000/01/01以降（≒指定された売上区分の過去全て）の売上を抽出する。
    -- 入金については、前回請求が有るものは前回請求日以降のものを、無ければ2000/01/01以降の入金を抽出する。
    -- 通常の請求は請求先から得意先が取得できるので、請求合計があれば必ず請求ヘッダもあるが、
    -- 電子決済は請求先と得意先が無関係なので、電子決済請求合計があっても電子決済請求ヘッダがあるとは限らない
    -- ※とは言え、合計もヘッダも、売上と入金のいずれかが存在すれば作成するので、必ずどちらも存在することになるはず。
    (SELECT
        D.得意先ＣＤ
        ,ISNULL(UA.売上金額, 0) AS 売上金額
        ,ISNULL(NA.入金額, 0) AS 入金額
    FROM
        -- 駆動表① 売上が存在する得意先
        (SELECT
            U1.得意先ＣＤ
        FROM
            売上ヘッダ AS U1
            INNER JOIN 売上明細 AS UM1
                ON UM1.企業ＣＤ = U1.企業ＣＤ
                AND UM1.売上日 = U1.売上日
                AND UM1.得意先ＣＤ = U1.得意先ＣＤ
                AND UM1.部署ＣＤ = U1.部署ＣＤ
            LEFT JOIN
                -- 前回締日
                (SELECT
                    H1.得意先ＣＤ
                    ,MAX(H1.請求日) AS 前回締日
                FROM
                    電子決済請求ヘッダ AS H1
                    INNER JOIN 電子決済請求合計 AS G1 ON H1.企業ＣＤ = G1.企業ＣＤ AND H1.請求番号 = G1.請求番号
                WHERE
                    H1.企業ＣＤ = @企業ＣＤ
                    AND H1.請求日 < @請求日                 -- 今回締日（入力された請求日）
                GROUP BY
                    H1.得意先ＣＤ
                ) AS M1 ON
                    M1.得意先ＣＤ = U1.得意先ＣＤ
        WHERE
            U1.企業ＣＤ = @企業ＣＤ
            -- 前回請求が有るものは前回請求日以降
            -- 無ければ過去の売上全て
            AND U1.売上日 > ISNULL(M1.前回締日, '2000/01/01')
            AND U1.売上日 <= @請求日            -- 今回締日（入力された請求日）
            AND UM1.売上区分 = @売上区分        -- 画面で指定された売上区分
            AND UM1.TP決済番号 IS NOT NULL      -- Tapionで決済済み
            AND UM1.TP取消決済番号 IS NULL      -- 取り消されていない
        UNION
        -- 駆動表② 入金が存在する得意先
        SELECT
            N1.得意先ＣＤ
        FROM
            入金明細 AS N1
            LEFT JOIN
                -- 前回締日
                (SELECT
                    H1.得意先ＣＤ
                    ,MAX(H1.請求日) AS 前回締日
                FROM
                    電子決済請求ヘッダ AS H1
                    INNER JOIN 電子決済請求合計 AS G1 ON H1.企業ＣＤ = G1.企業ＣＤ AND H1.請求番号 = G1.請求番号
                WHERE
                    H1.企業ＣＤ = @企業ＣＤ
                    AND H1.請求日 < @請求日                 -- 今回締日（入力された請求日）
                GROUP BY
                    H1.得意先ＣＤ
                ) AS M2 ON
                    M2.得意先ＣＤ = N1.得意先ＣＤ
        WHERE
            N1.企業ＣＤ = @企業ＣＤ
            AND N1.入金日 > ISNULL(M2.前回締日, '2000/01/01')
            AND N1.入金日 <= @請求日            -- 今回締日（入力された請求日）
            AND N1.入金方法 = @入金方法Tapion   -- 9:Tapion
            AND N1.TP決済番号 IS NOT NULL       -- Tapionで決済済み
            AND N1.TP取消決済番号 IS NULL       -- 取り消されていない
        ) AS D
        LEFT JOIN
        -- 売上
        (SELECT
            U1.得意先ＣＤ
            ,SUM(UM1.値引後金額) AS 売上金額
        FROM
            売上ヘッダ AS U1
            INNER JOIN 売上明細 AS UM1
                ON UM1.企業ＣＤ = U1.企業ＣＤ
                AND UM1.売上日 = U1.売上日
                AND UM1.得意先ＣＤ = U1.得意先ＣＤ
                AND UM1.部署ＣＤ = U1.部署ＣＤ
            LEFT JOIN
                -- 前回締日
                (SELECT
                    H1.得意先ＣＤ
                    ,MAX(H1.請求日) AS 前回締日
                FROM
                    電子決済請求ヘッダ AS H1
                    INNER JOIN 電子決済請求合計 AS G1 ON H1.企業ＣＤ = G1.企業ＣＤ AND H1.請求番号 = G1.請求番号
                WHERE
                    H1.企業ＣＤ = @企業ＣＤ
                    AND H1.請求日 < @請求日                 -- 今回締日（入力された請求日）
                GROUP BY
                    H1.得意先ＣＤ
                ) AS M1 ON
                    M1.得意先ＣＤ = U1.得意先ＣＤ
        WHERE
            U1.企業ＣＤ = @企業ＣＤ
            -- 前回請求が有るものは前回請求日以降
            -- 無ければ過去の売上全て
            AND U1.売上日 > ISNULL(M1.前回締日, '2000/01/01')
            AND U1.売上日 <= @請求日                -- 今回締日（入力された請求日）
            AND UM1.売上区分 = @売上区分            -- 画面で指定された売上区分
            AND UM1.TP決済番号 IS NOT NULL          -- Tapionで決済済み
            AND UM1.TP取消決済番号 IS NULL          -- 取り消されていない
        GROUP BY
            U1.得意先ＣＤ
        ) AS UA ON
            D.得意先ＣＤ = UA.得意先ＣＤ
        LEFT JOIN
        -- 入金
        (SELECT
            N1.得意先ＣＤ
            ,SUM(N1.入金額) AS 入金額
        FROM
            入金明細 AS N1
            LEFT JOIN
                -- 前回締日
                (SELECT
                    H1.得意先ＣＤ
                    ,MAX(H1.請求日) AS 前回締日
                FROM
                    電子決済請求ヘッダ AS H1
                    INNER JOIN 電子決済請求合計 AS G1 ON H1.企業ＣＤ = G1.企業ＣＤ AND H1.請求番号 = G1.請求番号
                WHERE
                    H1.企業ＣＤ = @企業ＣＤ
                    AND H1.請求日 < @請求日                 -- 今回締日（入力された請求日）
                GROUP BY
                    H1.得意先ＣＤ
                ) AS M2 ON
                    M2.得意先ＣＤ = N1.得意先ＣＤ
        WHERE
            N1.企業ＣＤ = @企業ＣＤ
            AND N1.入金日 > ISNULL(M2.前回締日, '2000/01/01')
            AND N1.入金日 <= @請求日            -- 今回締日（入力された請求日）
            AND N1.入金方法 = @入金方法Tapion   -- 9:Tapion
            AND N1.TP決済番号 IS NOT NULL       -- Tapionで決済済み
            AND N1.TP取消決済番号 IS NULL       -- 取り消されていない
        GROUP BY
            N1.得意先ＣＤ
        ) AS NA ON
            D.得意先ＣＤ = NA.得意先ＣＤ
    ) AS B
    INNER JOIN 得意先マスタ AS T ON T.企業ＣＤ = @企業ＣＤ AND T.得意先ＣＤ = B.得意先ＣＤ



