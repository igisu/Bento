    企業ＣＤ
    ,請求番号
    ,得意先ＣＤ
    ,部署ＣＤ
    ,得意先名
    ,請求日
    ,請求先ＣＤ
    ,請求先名
    ,売上金額
    ,入金額
    ,作成担当者ＣＤ
    ,作成日
    ,修正担当者ＣＤ
    ,修正日
) SELECT
    C.企業ＣＤ
    ,C.請求番号
    ,A.得意先ＣＤ
    ,A.部署ＣＤ
    ,A.得意先名
    ,A.請求日
    ,A.請求先ＣＤ
    ,A.請求先名
    ,A.売上金額
    ,A.入金額
    ,@作成担当者ＣＤ AS 作成担当者ＣＤ
    ,getdate()
    ,@修正担当者ＣＤ AS 修正担当者ＣＤ
    ,getdate()
FROM
    (SELECT
        得意先ＣＤ
        ,部署ＣＤ
        ,得意先名
        ,請求日
        ,請求先ＣＤ
        ,請求先名
        ,SUM(売上金額) AS 売上金額
        ,SUM(入金額) AS 入金額
    FROM
        #電子決済請求ヘッダTemp
    GROUP BY
        得意先ＣＤ
        ,部署ＣＤ
        ,得意先名
        ,請求日
        ,請求先ＣＤ
        ,請求先名
    ) AS A
    INNER JOIN #電子決済請求合計Temp AS B ON
        A.請求先ＣＤ = B.請求先ＣＤ AND A.請求日 = B.請求日
    INNER JOIN 電子決済請求合計 AS C ON
        B.請求先ＣＤ = C.請求先ＣＤ AND B.請求日 = C.請求日 AND C.企業ＣＤ = @企業ＣＤ



