-- 短冊印刷_データ作成済み確認
SELECT
    COUNT(A.出荷番号) AS CNT
FROM
    SP_T_出荷明細 AS A
WHERE
    A.企業ＣＤ = @企業ＣＤ
    AND A.部署ＣＤ = @部署ＣＤ
    AND A.喫食日 = @注文日          -- 注文日と配送日はどちらかのみ指定
    AND A.配送日 = @配送日          -- 注文日と配送日はどちらかのみ指定
    AND A.コースＣＤ = @コースＣＤ
    AND A.得意先ＣＤ = @得意先ＣＤ
    -- 印刷順に該当する食事区分CDを検索条件にする
    AND A.食事区分 IN (SELECT
                           食事区分ＣＤ
                       FROM
                           短冊集計設定マスタ
                       WHERE
                           企業ＣＤ = @企業ＣＤ
                           AND 部署ＣＤ = @部署ＣＤ
                           AND 印刷順 >= @印刷順From
                           AND 印刷順 <= @印刷順To
                      )
