    LEFT JOIN 得意先マスタ AS T ON T.企業ＣＤ = C.企業ＣＤ AND T.得意先ＣＤ = C.得意先ＣＤ
    LEFT JOIN 部署マスタ AS B ON B.企業ＣＤ = C.企業ＣＤ AND B.部署ＣＤ = @部署ＣＤ
    LEFT JOIN コースマスタ AS CM ON CM.企業ＣＤ = C.企業ＣＤ AND CM.コースＣＤ = @コースＣＤ
-- ②駆動表に紐付く注文（注文元の数量は配送先に集約する）
    LEFT JOIN
        -- ②注文の部品（各商品を分割した部品ごとに合計する）
        (SELECT
            C.得意先ＣＤ
            ,PART.弁当区分
            ,PART.コースＣＤ
            ,PART.部品ＣＤ AS 商品ＣＤ
            ,SUM(PART.商品数量) AS 商品数量
        FROM
            駆動表 AS C
            INNER JOIN
                -- ②－１ 弁当の主食
                (SELECT
                    @弁当区分主食 AS 弁当区分
                    ,H.コースＣＤ
                    ,H.得意先ＣＤ
        --              ,M.商品ＣＤ
                    ,I.主食ＣＤ AS 部品ＣＤ
                    ,SUM(D.商品数量) AS 商品数量
                FROM
                    注文ヘッダ AS H
                    INNER JOIN 注文明細 AS D
                        ON D.企業ＣＤ    = H.企業ＣＤ
                        AND D.注文区分   = H.注文区分
                        AND D.喫食日     = H.喫食日
                        AND D.得意先ＣＤ = H.得意先ＣＤ
                        AND D.部署ＣＤ   = H.部署ＣＤ
                    INNER JOIN 商品マスタ AS I
                        ON I.企業ＣＤ = D.企業ＣＤ
                        AND ISNULL(I.無効フラグ, 0) = 0
                        AND I.商品ＣＤ = D.商品ＣＤ
                WHERE
                    H.企業ＣＤ = @企業ＣＤ
                    AND H.注文区分 = @注文区分注文
                    AND H.喫食日 = @注文日
                    AND H.部署ＣＤ = @部署ＣＤ
                    AND H.コースＣＤ = @コースＣＤ
                    AND ISNULL(I.弁当区分, 0) = @弁当区分弁当   -- 弁当
                    AND ISNULL(I.主食ＣＤ, 0) <> 0              -- 主食がある
                    AND ISNULL(I.主食ＣＤ, 0) <> I.商品ＣＤ     -- 自分以外(主食の場合、主食ＣＤに自分自身の商品ＣＤが入っていることがあるので念のため)
                GROUP BY
                    H.コースＣＤ
                    ,H.得意先ＣＤ
        --              ,M.商品ＣＤ
                    ,I.主食ＣＤ
                UNION ALL   -- SUM()の対象にするので、同一部署、同一コース、同一部品ＣＤ、同一売上日、同一商品数量を同一視せずに全て抽出する（以下同様）
                -- ③－２ 弁当の副食
                SELECT
                    @弁当区分副食 AS 弁当区分
                    ,H.コースＣＤ
                    ,H.得意先ＣＤ
        --              ,M.商品ＣＤ
                    ,I.副食ＣＤ AS 部品ＣＤ
                    ,SUM(D.商品数量) AS 商品数量
                FROM
                    注文ヘッダ AS H
                    INNER JOIN 注文明細 AS D
                        ON D.企業ＣＤ    = H.企業ＣＤ
                        AND D.注文区分   = H.注文区分
                        AND D.喫食日     = H.喫食日
                        AND D.得意先ＣＤ = H.得意先ＣＤ
                        AND D.部署ＣＤ   = H.部署ＣＤ
                    INNER JOIN 商品マスタ AS I
                        ON I.企業ＣＤ = D.企業ＣＤ
                        AND ISNULL(I.無効フラグ, 0) = 0
                        AND I.商品ＣＤ = D.商品ＣＤ
                WHERE
                    H.企業ＣＤ = @企業ＣＤ
                    AND H.注文区分 = @注文区分注文
                    AND H.喫食日 = @注文日
                    AND H.部署ＣＤ = @部署ＣＤ
                    AND H.コースＣＤ = @コースＣＤ
                    AND ISNULL(I.弁当区分, 0) = @弁当区分弁当   -- 弁当
                    AND ISNULL(I.副食ＣＤ, 0) <> 0              -- 副食がある
                    AND ISNULL(I.副食ＣＤ, 0) <> I.商品ＣＤ     -- 自分以外(副食の場合、副食ＣＤに自分自身の商品ＣＤが入っていることがあるので念のため)
                GROUP BY
                    H.コースＣＤ
                    ,H.得意先ＣＤ
        --              ,M.商品ＣＤ
                    ,I.副食ＣＤ
                UNION ALL
                -- ②－３ 主食のみ
                SELECT
                    @弁当区分主食 AS 弁当区分
                    ,H.コースＣＤ
                    ,H.得意先ＣＤ
        --              ,M.商品ＣＤ
                    ,I.商品ＣＤ AS 部品ＣＤ
                    ,SUM(D.商品数量) AS 商品数量
                FROM
                    注文ヘッダ AS H
                    INNER JOIN 注文明細 AS D
                        ON D.企業ＣＤ    = H.企業ＣＤ
