SELECT DISTINCT
    T.得意先ＣＤ
    ,T.ソート順
    ,T.備考
FROM
-- ①駆動表
    駆動表 AS C
    INNER JOIN
        (SELECT
            企業ＣＤ
            ,得意先ＣＤ
            ,備考1 AS 備考
            ,1 AS ソート順
        FROM
            得意先マスタ
        WHERE
            LEN(ISNULL(備考1, '')) <> 0
        UNION
        SELECT
            企業ＣＤ
            ,得意先ＣＤ
            ,備考2 AS 備考
            ,2 AS ソート順
        FROM
            得意先マスタ
        WHERE
            LEN(ISNULL(備考2, '')) <> 0
        UNION
        SELECT
            企業ＣＤ
            ,得意先ＣＤ
            ,備考3 AS 備考
            ,3 AS ソート順
        FROM
            得意先マスタ
        WHERE
            LEN(ISNULL(備考3, '')) <> 0
        ) AS T ON T.企業ＣＤ = C.企業ＣＤ AND T.得意先ＣＤ = C.得意先ＣＤ
ORDER BY
    T.得意先ＣＤ
    ,T.ソート順


@企業ＣＤ = 40000
@部署ＣＤ = 1           -- 配送先の場合は99
@コースＣＤ = 101       -- 配送先の場合は4310 or 4311
@注文日 = '2026/03/11'
@注文区分注文 = 0
@弁当区分弁当 = 0
@弁当区分副食 = 1
@弁当区分主食 = 2
@弁当区分チケット = 8
@弁当区分その他 = 9
