                        AND D.喫食日     = H.喫食日
                        AND D.得意先ＣＤ = H.得意先ＣＤ
                        AND D.部署ＣＤ   = H.部署ＣＤ
                    INNER JOIN 商品マスタ AS I
                        ON I.企業ＣＤ = D.企業ＣＤ
                        AND ISNULL(I.無効フラグ, 0) = 0
                        AND I.商品ＣＤ = D.商品ＣＤ
                WHERE
