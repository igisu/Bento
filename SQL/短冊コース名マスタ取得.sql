-- 短冊コース名マスタ取得
-- 短冊コース名マスタが存在すればそれから、存在しなければコースマスタからコース名を取得する
-- したがってコースマスタに対して短冊コース名マスタを外部結合する（短冊コース名マスタのレコードは必要な場合にしか作られないので）
SELECT
    CM.企業ＣＤ
    ,CM.コースＣＤ
    ,CM.コース名
    ,TC.短冊印刷コース名
    ,TC.作成担当者ＣＤ
    ,A1.担当者名 AS 作成担当者名
    ,TC.作成日
    ,TC.修正担当者ＣＤ
    ,A2.担当者名 AS 修正担当者名
    ,TC.修正日
FROM
    コースマスタ AS CM
    LEFT JOIN 短冊コース名マスタ AS TC ON TC.企業ＣＤ = CM.企業ＣＤ AND TC.コースＣＤ = CM.コースＣＤ
    LEFT JOIN 担当者マスタ  AS A1 ON A1.企業ＣＤ = TC.企業ＣＤ AND TC.作成担当者ＣＤ = A1.担当者ＣＤ
    LEFT JOIN 担当者マスタ  AS A2 ON A2.企業ＣＤ = TC.企業ＣＤ AND TC.修正担当者ＣＤ = A2.担当者ＣＤ
WHERE
    CM.企業ＣＤ = @企業ＣＤ
    AND CM.コースＣＤ = @コースＣＤ
