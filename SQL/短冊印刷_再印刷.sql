-- 短冊印刷_再印刷
-- 出荷明細から取得する
-- 全く出力されない または データ作成＆印刷で出力したものより足りない場合は、データ作成していない条件で再印刷している疑いが濃厚。

SELECT
    A.喫食日
    ,A.部署ＣＤ
    ,A.配送日
    ,A.得意先ＣＤ
    ,A.得意先名
    ,A.グループ表記 AS 食事区分別食数
    ,A.コースＣＤ
    ,A.コース名
    ,A.コース順
    ,TSM.集計印刷名
    ,A.集計注文数 AS 数量
    ,TSM.袋計算フラグ
    ,A.食事区分
    ,TSM.集計印刷名 + '  ' + cast(A.集計注文数 as varchar) + ' 食' as 食数
    ,A.出荷番号 AS 明細出荷番号
    ,A.個口数
    ,cast(NULL AS varchar) AS 出荷番号      -- 小口数をMaxとするループ回数と明細出荷番号から算出する
    -- プログラムにて袋計算フラグと数量から算出した「袋数」を追加する
FROM
    SP_T_出荷明細 AS A
    -- 出荷明細を再作成した場合は同じデータでも新しい出荷番号が採番されるので、最新の出荷番号を取得する必要がある
    INNER JOIN
        (SELECT
            企業ＣＤ
            ,配送日
            ,部署ＣＤ
            ,コースＣＤ
            ,得意先ＣＤ
            ,喫食日
            ,食事区分
            ,MAX(出荷番号) AS 出荷番号
        FROM
            SP_T_出荷明細
        WHERE
            企業ＣＤ = @企業ＣＤ
            AND 部署ＣＤ = @部署ＣＤ
            AND 喫食日 = @注文日                  -- 注文日と配送日はどちらかのみ指定
            AND 配送日 = @配送日                  -- 注文日と配送日はどちらかのみ指定
        GROUP BY
            企業ＣＤ
            ,配送日
            ,部署ＣＤ
            ,コースＣＤ
            ,得意先ＣＤ
            ,喫食日
            ,食事区分
        ) AS A2
        ON A.企業ＣＤ = A2.企業ＣＤ
        AND A.出荷番号 = A2.出荷番号
    INNER JOIN 短冊集計設定マスタ AS TSM
        ON TSM.企業ＣＤ  = A.企業ＣＤ
        AND TSM.部署ＣＤ = A.部署ＣＤ
        AND TSM.食事区分ＣＤ = A.食事区分
WHERE
    1 = 1
    AND A.コースＣＤ = @コースＣＤ
    AND A.得意先ＣＤ = @得意先ＣＤ
    -- 印刷順に該当する食事区分CDを検索条件にする
    AND A.食事区分 IN (SELECT
                            食事区分ＣＤ
                        FROM
                            短冊集計設定マスタ
                        WHERE
                            企業ＣＤ = @企業ＣＤ
                            AND 部署ＣＤ = @部署ＣＤ
                            AND 印刷順 >= @印刷順From
                            AND 印刷順 <= @印刷順To
                       )
ORDER BY
    TSM.印刷順
    ,A.コースＣＤ
    ,A.コース順
    ,A.得意先ＣＤ
