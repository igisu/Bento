-- 生産予定数入力（商品）
SELECT
    企業ＣＤ
    ,商品ＣＤ
    ,部署グループ
    ,商品名
    ,商品名略称
    ,商品名記号
    ,商品単価税込
    ,商品単価税抜
    ,弁当区分
    ,主食ＣＤ
    ,副食ＣＤ
    ,部数単位
    ,食事区分
    ,軽減税率フラグ
    ,無効フラグ
FROM
    商品マスタ
WHERE
    企業ＣＤ = @企業ＣＤ
    AND ISNULL(無効フラグ, 0) = 0
UNION
    -- 企業ＣＤと部署ＣＤと喫食日に該当するレコードを生産予定テーブルから取得
SELECT
    商品ＣＤ
FROM
    生産予定
WHERE
    企業ＣＤ = @企業ＣＤ
    AND 部署ＣＤ = @部署ＣＤ
    AND 喫食日 = @喫食日
ORDER BY
    商品ＣＤ
