-- コースマスタと臨時コースマスタから取得

-- コースマスタから取得（実施日に該当する臨時コースマスタがあればコースマスタからは取得しない。無ければ取得する）
SELECT
    C.企業ＣＤ
    ,C.コースＣＤ
    ,C.コース区分
    ,C.コース名
    ,C.部署ＣＤ
    ,C.担当者ＣＤ
    ,C.工場フラグ
    ,C.無効フラグ
    ,C.作成担当者ＣＤ
    ,C.作成日
    ,C.修正担当者ＣＤ
    ,C.修正日
FROM
    コースマスタ AS C
    LEFT JOIN
        (SELECT
            コースＣＤ
        FROM
            臨時コースマスタ
        WHERE
            企業ＣＤ = 1
            AND ISNULL(無効フラグ, 0) = 0
            AND コースＣＤ = 6
            AND 実施日 = '2016/05/12'
--            AND 実施日 = '2016/05/13'
        ) AS RM
        ON RM.コースＣＤ = C.コースＣＤ
WHERE
    C.企業ＣＤ = 1
    AND C.コースＣＤ = 6
    AND ISNULL(C.無効フラグ, 0) = 0
    AND RM.コースＣＤ IS NULL
-- 臨時コーステーブルから取得（実施日に該当する臨時コーステーブルがあれば取得する。無ければ取得しない）
UNION
SELECT
    RM.企業ＣＤ
    ,RM.コースＣＤ
    ,RM.コース区分
    ,RM.コース名
    ,RM.部署ＣＤ
    ,RM.担当者ＣＤ
    ,RM.工場フラグ
    ,RM.無効フラグ
    ,RM.作成担当者ＣＤ
    ,RM.作成日
    ,RM.修正担当者ＣＤ
    ,RM.修正日
FROM
    臨時コーステーブル AS RT
    INNER JOIN 臨時コースマスタ AS RM ON RM.企業ＣＤ = RT.企業ＣＤ AND RM.コースＣＤ = RT.コースＣＤ AND RT.実施日 = RM.実施日 AND ISNULL(RM.無効フラグ, 0) = 0
WHERE
    RT.企業ＣＤ = 1
    AND RT.コースＣＤ = 6
    AND ISNULL(RT.無効フラグ, 0) = 0
    AND RT.実施日 = '2016/05/12'
--    AND RT.実施日 = '2016/05/13'
