--- 月次売上集計作成
--- 売上から得意先単位で作成

--- 月次売上集計を削除
DELETE FROM 月次売上集計
WHERE 企業ＣＤ = @企業ＣＤ
AND 集計年 = @集計年
AND 集計月 = @集計月
AND 部署ＣＤ = @部署ＣＤ


--- 月次売上集計に出力
INSERT INTO 月次売上集計 (
    企業ＣＤ
    ,集計年
    ,集計月
    ,部署ＣＤ
    ,得意先ＣＤ
    ,商品ＣＤ
    ,得意先名
    ,今月売上額
    ,今月数量
    ,今月値引額
    ,作成担当者ＣＤ
    ,作成日
    ,修正担当者ＣＤ
    ,修正日
)SELECT
    UM.企業ＣＤ
    ,@集計年
    ,@集計月
    ,UM.部署ＣＤ
    ,UM.得意先ＣＤ
    ,UM.商品ＣＤ
    ,T.得意先名
    ,UM.今月売上額
    ,UM.今月数量
    ,UM.今月値引額
    ,@作成担当者ＣＤ
    ,getdate()
    ,@修正担当者ＣＤ
    ,getdate()
FROM
    (SELECT
        企業ＣＤ
        ,部署ＣＤ
        ,得意先ＣＤ
        ,商品ＣＤ
        ,SUM((商品単価 * 商品数量) - ISNULL(値引額, 0)) AS 今月売上額
        ,SUM(商品数量) AS 今月数量
        ,SUM(値引額) AS 今月値引額
    FROM
        売上明細
    WHERE
        企業ＣＤ = @企業ＣＤ
        AND 部署ＣＤ = @部署ＣＤ
        AND 売上日 >= @対象年月一日
        AND 売上日 <= @対象年月末日
        AND ISNULL(チケット束フラグ, 0) = 0
    GROUP BY
        企業ＣＤ
        ,部署ＣＤ
        ,得意先ＣＤ
        ,商品ＣＤ
    ) AS UM
    LEFT JOIN 得意先マスタ AS T ON T.企業ＣＤ = UM.企業ＣＤ AND T.得意先ＣＤ = UM.得意先ＣＤ


@企業ＣＤ = 40001
@集計年 = 2017
@集計月 = 5
@部署ＣＤ = 1
@対象年月一日 = '2017/05/01'
@対象年月末日 = '2017/05/31'
@作成担当者ＣＤ = 1
@修正担当者ＣＤ = 1
