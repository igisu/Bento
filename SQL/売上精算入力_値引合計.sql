-- 売上精算入力_値引合計
SELECT
    ISNULL(SUM(M.値引額), 0) AS 値引額
FROM
    売上ヘッダ AS H
    INNER JOIN 売上明細 AS M
        ON  M.企業ＣＤ   = H.企業ＣＤ
        AND M.売上日     = H.売上日
        AND M.得意先ＣＤ = H.得意先ＣＤ
        AND M.部署ＣＤ   = H.部署ＣＤ
WHERE
    H.企業ＣＤ       = @企業ＣＤ
    AND H.売上日     = @精算日
    AND H.部署ＣＤ   = @部署ＣＤ
    AND H.コースＣＤ = @コースＣＤ
    -- 以下の値引きを除く
    -- ・現金のチケット束売りの値引き
    -- ・Tapionのチケット束売りの値引き
    -- ・バークレーの値引き
    -- （現金でもTapionでもないか、(現金またはTapionでも)チケット束売りではないもの かつ バークレーでもないものを抽出）
    AND ((M.売上区分 NOT IN (@売上区分現金, @売上区分LINE) OR ISNULL(M.チケット束フラグ, 0) = 0) AND M.売上区分 <> @売上区分バークレー)

@売上区分現金 = 0
@売上区分バークレー = 3
@売上区分LINE = 5
