-- 月次売掛残高一覧
SELECT
    A.企業ＣＤ
    ,A.集計年
    ,A.集計月
    ,A.部署ＣＤ
    ,B.部署名
    ,C.コースＣＤ
    ,C.コース名
    ,A.請求先ＣＤ
    ,A.請求先名
    ,A.先月売掛残高
    ,A.今月入金額
    ,A.今月売上額
    ,A.今月売掛残高
    ,A.作成担当者ＣＤ
    ,A.作成日
    ,A.修正担当者ＣＤ
    ,A.修正日
    ,S.締区分
    ,S.月締日
    ,VS.締め区分名
FROM
    月次売掛残高集計 AS A
    -- 分配先の売上は分配元として計上したいので、得意先ＣＤを分配元のそれにすり替える
    INNER JOIN 得意先マスタ AS S ON S.企業ＣＤ = A.企業ＣＤ AND S.得意先ＣＤ = A.請求先ＣＤ
    INNER JOIN 得意先マスタ AS J ON J.企業ＣＤ = S.企業ＣＤ AND J.得意先ＣＤ = ISNULL(S.受注得意先ＣＤ, S.得意先ＣＤ)

    -- コースによる絞り込み用
    -- 同じ得意先に複数のコースが設定されている場合、そのいずれのコースを条件に指定しても、そのコースにぶら下がる得意先がヒットしないといけない。
    INNER JOIN
        (SELECT DISTINCT
            CM.企業ＣＤ
            ,CM.部署ＣＤ
            ,CM.コース名
            ,CM.コースＣＤ
            ,CT.得意先ＣＤ
            ,CT.コース順
        FROM
            コースマスタ AS CM
            INNER JOIN コーステーブル AS CT ON
                CM.企業ＣＤ = CT.企業ＣＤ
                AND CM.コースＣＤ =  CT.コースＣＤ
        WHERE
            CT.コースＣＤ = @コースＣＤ
        ) AS C
        ON J.企業ＣＤ = C.企業ＣＤ
        AND A.部署ＣＤ = C.部署ＣＤ     -- 月次売掛残高集計の部署と一致するものに限る
        AND J.得意先ＣＤ = C.得意先ＣＤ

    -- 検索条件にコースが指定されていない場合は、ヒットした得意先が持つコースのうち最小値を取得する
    LEFT JOIN
        (SELECT
            CM.企業ＣＤ
            ,CM.部署ＣＤ
            ,CM.コース名
            ,CT1.コースＣＤ
            ,CT1.得意先ＣＤ
            ,CT1.コース順
        FROM
            コーステーブル AS CT1
            INNER JOIN
                (SELECT
                    M.企業ＣＤ
                    ,M.部署ＣＤ
                    ,T.得意先ＣＤ
                    ,MIN(T.コースＣＤ) AS コースＣＤ
                FROM
                    コースマスタ AS M
                    LEFT JOIN コーステーブル AS T ON
                        T.企業ＣＤ = M.企業ＣＤ
                        AND T.コースＣＤ = M.コースＣＤ
                GROUP BY
                    M.企業ＣＤ
                    ,M.部署ＣＤ
                    ,T.得意先ＣＤ
                ) AS CT2
                    ON CT2.企業ＣＤ = CT1.企業ＣＤ
                    AND CT2.得意先ＣＤ = CT1.得意先ＣＤ
                    AND CT2.コースＣＤ = CT1.コースＣＤ
            INNER JOIN コースマスタ AS CM
                ON CM.企業ＣＤ = CT1.企業ＣＤ
                AND CM.コースＣＤ =  CT1.コースＣＤ
        ) AS C
        ON J.企業ＣＤ = C.企業ＣＤ
        AND A.部署ＣＤ = C.部署ＣＤ     -- 月次売掛残高集計の部署と一致するものに限る
        AND J.得意先ＣＤ = C.得意先ＣＤ

    LEFT JOIN 部署マスタ AS B
        ON B.企業ＣＤ = A.企業ＣＤ
        AND B.部署ＣＤ = A.部署ＣＤ
        AND T.得意先ＣＤ = A.請求先ＣＤ
    LEFT JOIN V_締め区分 AS VS ON VS.締め区分CD = S.締区分
WHERE
    A.企業ＣＤ = @企業ＣＤ
    AND A.集計年 = @集計年
    AND A.集計月 = @集計月
    AND A.部署ＣＤ = @部署ＣＤ
    AND A.請求先ＣＤ = @請求先ＣＤ
ORDER BY
    A.請求先ＣＤ


@企業ＣＤ = 40001
@集計年 = 2017
@集計月 = 4
@部署ＣＤ = 1
@請求先ＣＤ = 94
