-- 短冊印刷_出荷明細取得
SELECT
    A.企業ＣＤ
    ,A.出荷番号
    ,A.配送日
    ,A.部署ＣＤ
    ,ISNULL(A.コースＣＤ, -1) AS コースＣＤ     -- 比較用に変換する
    ,A.コース名
    ,A.コース順
    ,A.得意先ＣＤ
    ,A.得意先名
    ,A.喫食日
    ,A.食事区分
    ,A.集計注文数
    ,A.袋数表記
    ,A.グループ表記
    ,A.グループ表記比較用
    ,A.個口数
    ,A.作成担当者ＣＤ
    ,A1.担当者名 AS 作成担当者名
    ,A.作成日
    ,A.修正担当者ＣＤ
    ,A2.担当者名 AS 修正担当者名
    ,A.修正日
FROM
    SP_T_出荷明細 AS A
    LEFT JOIN 担当者マスタ AS A1 ON A1.企業ＣＤ = @企業ＣＤ AND A.作成担当者ＣＤ = A1.担当者ＣＤ
    LEFT JOIN 担当者マスタ AS A2 ON A2.企業ＣＤ = @企業ＣＤ AND A.修正担当者ＣＤ = A2.担当者ＣＤ
WHERE
    A.企業ＣＤ = @企業ＣＤ
    AND A.部署ＣＤ = @部署ＣＤ
    AND A.喫食日 = @注文日          -- 注文日と配送日はどちらかのみ指定
    AND A.配送日 = @配送日          -- 注文日と配送日はどちらかのみ指定
    AND A.コースＣＤ = @コースＣＤ
    AND A.得意先ＣＤ = @得意先ＣＤ
    -- 印刷順に該当する食事区分CDを検索条件にする
    AND A.食事区分 IN (SELECT
                           食事区分ＣＤ
                       FROM
                           短冊集計設定マスタ
                       WHERE
                           企業ＣＤ = @企業ＣＤ
                           AND 部署ＣＤ = @部署ＣＤ
                           AND 印刷順 >= @印刷順From
                           AND 印刷順 <= @印刷順To
                      )
ORDER BY
    A.出荷番号
