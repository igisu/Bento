-- 月次商品別売上一覧
SELECT
    U.部署ＣＤ
    ,B.部署名
    ,U.商品ＣＤ
    ,S.商品名
    ,U.数量
    ,U.金額
    ,FLOOR(U.平均単価) AS 平均単価
FROM
    (SELECT
        企業ＣＤ
        ,部署ＣＤ               -- 部署ごとに集計する場合はこちら
        ,NULL AS 部署ＣＤ       -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこちら
        ,商品ＣＤ
        ,SUM(今月数量) AS 数量
        ,SUM(今月売上額) AS 金額
        ,CASE WHEN SUM(今月数量) = 0 THEN 0 ELSE SUM(今月売上額) / SUM(今月数量) END AS 平均単価
    FROM
        月次売上集計
    WHERE
        企業ＣＤ = @企業ＣＤ
        AND 集計年 = @集計年
        AND 集計月 = @集計月
        AND 部署ＣＤ = @部署ＣＤ    -- 部署ごとに集計する場合のみ有効
        AND 商品ＣＤ = @商品ＣＤ
    GROUP BY
        企業ＣＤ
        ,部署ＣＤ               -- 部署ごとに集計しない（つまり部署を跨がって集計する）場合はこの行は不要
        ,商品ＣＤ
    ) AS U
    LEFT JOIN 部署マスタ AS B
        ON B.企業ＣＤ = U.企業ＣＤ
        AND B.部署ＣＤ = U.部署ＣＤ
    LEFT JOIN 商品マスタ AS S
        ON S.企業ＣＤ = U.企業ＣＤ
        AND S.商品ＣＤ = U.商品ＣＤ
ORDER BY
    U.部署ＣＤ
    ,U.商品ＣＤ
    ,U.数量
    ,U.金額
    ,U.平均単価


@企業ＣＤ = 40000
@集計年 = 2017
@集計月 = 3
@部署ＣＤ = 1
@商品ＣＤ = 19
