-- 売掛分配入力（更新対象売上明細取得）
-- 分配元取得
SELECT
    0 AS 分配元先区分
    ,M.企業ＣＤ
    ,M.売上日
    ,M.得意先ＣＤ
    ,M.部署ＣＤ
    ,M.明細番号
    ,M.商品ＣＤ
    ,M.商品グループＣＤ
    ,M.売上区分
    ,M.商品単価
    ,M.商品数量
    ,M.値引額
    ,M.値引事由区分
    ,M.値引前金額
    ,M.値引後金額
    ,M.消費税額
    ,M.商品金額合計税込
    ,M.計算税率
    ,M.チケット束フラグ
    ,M.現金補填フラグ
    ,M.主食ＣＤ
    ,M.副食ＣＤ
    ,M.食事区分
    ,M.分配元数量
    ,M.作成担当者ＣＤ
    ,M.作成日
    ,M.修正担当者ＣＤ
    ,M.修正日
FROM
    売上明細 AS M
WHERE
    M.企業ＣＤ = @企業ＣＤ
    AND M.売上日   = @売上日
    AND M.得意先ＣＤ = @得意先ＣＤ
    AND M.部署ＣＤ = @部署ＣＤ
UNION
SELECT
    1 AS 分配元先区分
    ,M.企業ＣＤ
    ,M.売上日
    ,M.得意先ＣＤ
    ,M.部署ＣＤ
    ,M.明細番号
    ,M.商品ＣＤ
    ,M.商品グループＣＤ
    ,M.売上区分
    ,M.商品単価
    ,M.商品数量
    ,M.値引額
    ,M.値引事由区分
    ,M.値引前金額
    ,M.値引後金額
    ,M.消費税額
    ,M.商品金額合計税込
    ,M.計算税率
    ,M.チケット束フラグ
    ,M.現金補填フラグ
    ,M.主食ＣＤ
    ,M.副食ＣＤ
    ,M.食事区分
    ,M.分配元数量
    ,M.作成担当者ＣＤ
    ,M.作成日
    ,M.修正担当者ＣＤ
    ,M.修正日
FROM
    売上明細 AS M
    INNER JOIN 得意先マスタ AS T
        ON T.企業ＣＤ  = M.企業ＣＤ
        AND T.得意先ＣＤ = M.得意先ＣＤ
WHERE
    T.企業ＣＤ = @企業ＣＤ
    AND T.受注得意先ＣＤ = @得意先ＣＤ
    AND M.売上日   = @売上日
    AND M.部署ＣＤ = @部署ＣＤ
ORDER BY
    分配元先区分
    ,M.得意先ＣＤ
    ,M.明細番号
