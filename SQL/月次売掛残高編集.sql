-- 月次売掛残高編集
SELECT
    Z0.企業ＣＤ
    ,Z0.集計年
    ,Z0.集計月
    ,Z0.部署ＣＤ
    ,B.部署名
    ,Z0.請求先ＣＤ
    ,Z0.請求先名
    ,Z0.先月売掛残高
    ,Z0.今月入金額
    ,Z0.今月売上額
    ,Z0.今月売掛残高
    ,Z0.作成担当者ＣＤ
    ,A1.担当者名 AS 作成担当者名
    ,Z0.作成日
    ,Z0.修正担当者ＣＤ
    ,A2.担当者名 AS 修正担当者名
    ,Z0.修正日
    ,Z1.集計年 AS 前回集計年
    ,Z1.集計月 AS 前回集計月
    ,Z1.先月売掛残高 AS 前回先月売掛残高
    ,Z1.今月入金額 AS 前回今月入金額
    ,Z1.今月売上額 AS 前回今月売上額
    ,Z1.今月売掛残高 AS 前回今月売掛残高
    ,Z2.集計年 AS 前々回集計年
    ,Z2.集計月 AS 前々回集計月
    ,Z2.先月売掛残高 AS 前々回先月売掛残高
    ,Z2.今月入金額 AS 前々回今月入金額
    ,Z2.今月売上額 AS 前々回今月売上額
    ,Z2.今月売掛残高 AS 前々回今月売掛残高
FROM
    月次売掛残高集計 AS Z0
    LEFT JOIN 月次売掛残高集計 AS Z1
        ON Z0.企業ＣＤ = Z1.企業ＣＤ
        AND Z0.部署ＣＤ = Z1.部署ＣＤ
        AND Z0.請求先ＣＤ = Z1.請求先ＣＤ
        AND Z1.集計年 = @前回集計年
        AND Z1.集計月 = @前回集計月
    LEFT JOIN 月次売掛残高集計 AS Z2
        ON Z0.企業ＣＤ = Z2.企業ＣＤ
        AND Z0.部署ＣＤ = Z2.部署ＣＤ
        AND Z0.請求先ＣＤ = Z2.請求先ＣＤ
        AND Z2.集計年 = @前々回集計年
        AND Z2.集計月 = @前々回集計月
    LEFT JOIN 部署マスタ AS B ON B.企業ＣＤ = Z0.企業ＣＤ AND B.部署ＣＤ = Z0.部署ＣＤ
    LEFT JOIN 担当者マスタ AS A1 ON A1.企業ＣＤ = Z0.企業ＣＤ AND Z0.作成担当者ＣＤ = A1.担当者ＣＤ
    LEFT JOIN 担当者マスタ AS A2 ON A2.企業ＣＤ = Z0.企業ＣＤ AND Z0.修正担当者ＣＤ = A2.担当者ＣＤ
WHERE
    Z0.企業ＣＤ = @企業ＣＤ
    AND Z0.部署ＣＤ = @部署ＣＤ
    AND Z0.請求先ＣＤ = @請求先ＣＤ
    AND Z0.集計年 = @集計年
    AND Z0.集計月 = @集計月
